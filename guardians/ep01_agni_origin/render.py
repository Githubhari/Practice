# ------------------------------------------------------------------ timeline
T_REWIND, T_PAST = 2.8, 3.6
T_LAMPS_OUT = 4.2
T_SHADOW, T_ABSORB, T_BLAST = 11.0, 17.0, 19.8
T_GROW, T_SPEAR, T_HERO, T_END = 21.0, 23.5, 26.0, 31.0
BOY_U, ADULT_U = 150, 290

SHAKES = [(0.3, 30), (T_REWIND, 10), (T_BLAST, 45), (T_SPEAR, 12), (27.0, 25), (32.0, 14)]


def shake(t):
    amp = sum(s * math.exp(-(t - ts) * 5) for ts, s in SHAKES if t >= ts)
    if 14.5 < t < T_BLAST:
        amp += 4 * prog(t, 14.5, T_BLAST)
    r = random.Random(int(t * FPS))
    return r.uniform(-amp, amp), r.uniform(-amp, amp)


# ------------------------------------------------------------------ static data
R = random.Random(21)
HUTS = []
x = -30
while x < W + 60:
    w = R.uniform(120, 190)
    if abs(x + w / 2 - 540) > 170:
        HUTS.append((x + w / 2, w, R.uniform(110, 170)))
    x += w + R.uniform(10, 40)
# lamps go out from the edges inward; relight from centre outward
HUT_ORDER = sorted(range(len(HUTS)), key=lambda k: -abs(HUTS[k][0] - 540))
STARS = [(R.uniform(0, W), R.uniform(0, 1100), R.uniform(0.8, 2.6), R.uniform(0, 6.3)) for _ in range(220)]
VORTEX = [(R.uniform(0, 6.283), R.uniform(60, 260), R.uniform(2, 6), R.uniform(0.6, 1.6),
           R.uniform(0, 1)) for _ in range(160)]
EMB = [(R.uniform(-1, 1), R.uniform(0, 1), R.uniform(150, 380), R.uniform(2, 6), R.uniform(0, 6.3))
       for _ in range(70)]


def lamp_level(k, t):
    """1 = lit, 0 = out, for hut k at time t."""
    order = HUT_ORDER.index(k)
    out_t = T_LAMPS_OUT + order * 0.38
    on_t = 26.4 + (len(HUTS) - 1 - order) * 0.2
    if t < out_t:
        return 1.0
    if t < on_t:
        return 1 - ease_io(prog(t, out_t, out_t + 0.15))
    return ease_out(prog(t, on_t, on_t + 0.3))


def stars_level(t):
    return ease_io(prog(t, 27.5, 30.0)) * 0.9


# ------------------------------------------------------------------ drawing
def sky(ctx, t, warm=0.0):
    g = cairo.LinearGradient(0, 0, 0, GROUND)
    g.add_color_stop_rgb(0, *hexc("#04020a"))
    g.add_color_stop_rgb(0.7, *kit.lerp_col(hexc("#1a0612"), hexc("#3a1406"), warm) if hasattr(kit, "lerp_col") else hexc("#1a0612"))
    g.add_color_stop_rgb(1, *(hexc("#2a0a10") if warm < 0.5 else hexc("#4a1a08")))
    ctx.set_source(g)
    ctx.rectangle(-300, -300, W + 600, H + 600)
    ctx.fill()
    a = stars_level(t)
    if a > 0:
        for sx, sy, r, ph in STARS:
            ctx.set_source_rgba(1, 1, 0.95, a * (0.6 + 0.4 * math.sin(t * 3 + ph)))
            ctx.arc(sx, sy, r, 0, TAU)
            ctx.fill()


def village(ctx, t):
    for k, (hx, w, h) in enumerate(HUTS):
        base = GROUND + 8
        lv = lamp_level(k, t)
        if lv > 0:
            glow(ctx, hx, base - h * 0.35, w * 0.9, hexc("#ffa040"), 0.35 * lv)
        ctx.set_source_rgb(0.03, 0.015, 0.02)
        ctx.rectangle(hx - w / 2, base - h * 0.6, w, h * 0.6)
        ctx.fill()
        ctx.move_to(hx - w * 0.62, base - h * 0.58)
        ctx.line_to(hx, base - h * 1.15)
        ctx.line_to(hx + w * 0.62, base - h * 0.58)
        ctx.close_path()
        ctx.fill()
        ww, wh = w * 0.2, h * 0.2
        wx, wy = hx - ww / 2, base - h * 0.42
        if lv > 0:
            ctx.set_source_rgba(1, 0.7, 0.3, lv)
            ctx.rectangle(wx, wy, ww, wh)
            ctx.fill()
            flick = 1 + 0.1 * math.sin(t * 13 + k)
            glow(ctx, hx, wy + wh / 2, 45 * flick, hexc("#ffb050"), 0.6 * lv)
        else:
            ctx.set_source_rgb(0.06, 0.04, 0.05)
            ctx.rectangle(wx, wy, ww, wh)
            ctx.fill()
    ctx.set_source_rgb(0.02, 0.01, 0.015)
    ctx.rectangle(-300, GROUND, W + 600, H)
    ctx.fill()


def diya(ctx, x, y, flame, t):
    """Clay oil lamp with a flame; flame 0..1+ scales the fire."""
    ctx.set_source_rgb(*hexc("#7a3b1c"))
    ctx.move_to(x - 30, y)
    ctx.curve_to(x - 26, y + 22, x + 26, y + 22, x + 30, y)
    ctx.line_to(x + 40, y - 6)
    ctx.line_to(x + 22, y - 4)
    ctx.close_path()
    ctx.fill()
    if flame <= 0:
        return
    fl = flame * (1 + 0.12 * math.sin(t * 23) + 0.08 * math.sin(t * 37))
    glow(ctx, x + 28, y - 18, 140 * fl, FIRE, 0.8)
    sway = 3 * math.sin(t * 9)
    for sc, col in ((1.0, FIRE), (0.6, GOLD), (0.3, (1, 1, 0.9))):
        h = 46 * fl * sc
        wdt = 13 * fl * sc
        bx, by = x + 30, y - 8
        ctx.move_to(bx - wdt, by)
        ctx.curve_to(bx - wdt, by - h * 0.5, bx + sway, by - h * 0.8, bx + sway * 1.5, by - h)
        ctx.curve_to(bx + sway, by - h * 0.8, bx + wdt, by - h * 0.5, bx + wdt, by)
        ctx.curve_to(bx + wdt, by + wdt * 0.8, bx - wdt, by + wdt * 0.8, bx - wdt, by)
        ctx.close_path()
        ctx.set_source_rgb(*col)
        ctx.fill()


def with_alpha(ctx, a, fn):
    if a <= 0:
        return None
    ctx.push_group()
    res = fn()
    ctx.pop_group_to_source()
    ctx.paint_with_alpha(a)
    return res


def boy_y(u):
    return GROUND - 0.95 * u


def scene_cold_open(ctx, t):
    ctx.set_source_rgb(*hexc("#1a0602"))
    ctx.paint()
    p = ease_out(prog(t, 0.25, 0.5))
    glow(ctx, W / 2, 900, 1000, FIRE, 0.3 + 0.5 * p)
    speed_lines(ctx, W / 2, 900, t, 0.25 * p, GOLD)
    z = 1.15 - 0.1 * t / T_REWIND
    ctx.save()
    ctx.translate(W / 2, 1300)
    ctx.scale(z, z)
    ctx.translate(-W / 2, -1300)
    ctx.set_source_rgb(0.02, 0.02, 0.03)
    ctx.rectangle(-200, 1400, W + 400, 800)
    ctx.fill()
    x, y, u = W / 2, 1400 - 0.95 * ADULT_U, ADULT_U
    hands = draw_hero(ctx, AGNI, x, y, u, t, p)
    kit.hero_fx_front(ctx, AGNI, t, t, x, y, u, p, hands)
    ctx.restore()
    if 0.3 <= t < 0.4:
        ctx.set_source_rgba(1, 0.9, 0.7, 0.8)
        ctx.paint()
    a = ease_io(prog(t, 1.0, 1.3))
    text(ctx, "How does a boy", W / 2, 360, 66, (1, 1, 1), a, FONT_BLACK, 2)
    text(ctx, "become FIRE?", W / 2, 450, 76, GOLD, a, FONT_BLACK, 4, glow_col=FIRE)


def scene_rewind(ctx, t):
    s = prog(t, T_REWIND, T_PAST)
    ctx.set_source_rgb(0.05, 0.04, 0.06)
    ctx.paint()
    speed_lines(ctx, W / 2, H / 2, t * 3, 0.5, (1, 1, 1))
    for k in range(14):
        y = random.Random(int(t * 60) + k).uniform(0, H)
        ctx.set_source_rgba(1, 1, 1, 0.15)
        ctx.rectangle(0, y, W, random.Random(k).uniform(2, 12))
        ctx.fill()
    a = ease_io(prog(t, T_REWIND + 0.1, T_REWIND + 0.3))
    text(ctx, "10 YEARS AGO", W / 2, 980, 92, (1, 1, 1), a, FONT_BLACK, 12)


def scene_past(ctx, t):
    """Village, lamps die, shadow comes, boy absorbs flame, blast, growth, hero."""
    # camera
    if t < T_SHADOW:
        z, cx, cy = 1.3 + 0.05 * prog(t, T_PAST, T_SHADOW), 540, 1250
    elif t < T_BLAST:
        p = ease_io(prog(t, T_SHADOW, T_ABSORB))
        z, cx, cy = lerp(1.35, 1.75, p), lerp(540, 600, p), lerp(1250, 1290, p)
    elif t < T_HERO:
        p = ease_io(prog(t, T_GROW, T_HERO))
        z, cx, cy = lerp(1.75, 1.15, p), lerp(600, 540, p), lerp(1290, 1150, p)
    else:
        p = ease_io(prog(t, T_HERO, T_END))
        z, cx, cy = lerp(1.15, 1.2, p), 540, 1150
    ctx.save()
    ctx.translate(W / 2, H / 2)
    ctx.scale(z, z)
    ctx.translate(-cx, -cy)

    warm = ease_io(prog(t, T_BLAST, T_BLAST + 1.5))
    sky(ctx, t, warm)
    village(ctx, t)

    # darkness tendrils sweeping the village
    if T_LAMPS_OUT - 0.5 < t < T_SHADOW + 1:
        a = prog(t, T_LAMPS_OUT - 0.5, T_LAMPS_OUT) * (1 - prog(t, T_SHADOW, T_SHADOW + 1))
        ctx.set_line_cap(cairo.LINE_CAP_ROUND)
        for k in range(8):
            yy = 1150 + k * 40
            ph = t * 1.4 + k
            ctx.set_source_rgba(0.02, 0.0, 0.03, 0.45 * a)
            ctx.set_line_width(40 - k * 3)
            ctx.move_to(-100, yy)
            for xx in range(-100, W + 120, 60):
                ctx.line_to(xx, yy + 50 * math.sin(xx * 0.008 + ph))
            ctx.stroke()

    # shadow creature
    if t >= T_SHADOW - 0.5 and t < T_BLAST + 0.6:
        come = ease_out(prog(t, T_SHADOW - 0.5, 14.0))
        blown = ease_out(prog(t, T_BLAST, T_BLAST + 0.6))
        vx = lerp(1350, 860, come) + 700 * blown
        alpha = 1 - blown
        def draw_shadow():
            return draw_villain(ctx, vx, 940, 0.42, t, ease_out(prog(t, 12.0, 12.3)), 0.8)
        eye = with_alpha(ctx, alpha, draw_shadow)
        # reaching tendril toward the flame
        if eye and 13.5 < t < T_BLAST:
            reach = ease_io(prog(t, 13.5, 16.2))
            fx, fy = 540 + 30, boy_y(BOY_U) - 0.6 * BOY_U - 30
            sx, sy = vx - 120, 1180
            ex, ey = lerp(sx, fx + 40, reach), lerp(sy, fy, reach)
            ctx.set_source_rgba(0.03, 0.0, 0.04, 0.95 * alpha)
            ctx.set_line_width(24)
            ctx.set_line_cap(cairo.LINE_CAP_ROUND)
            ctx.move_to(sx, sy)
            ctx.curve_to(sx - 80, sy - 160 + 30 * math.sin(t * 4), ex + 120, ey - 120, ex, ey)
            ctx.stroke()
            ctx.set_source_rgba(1, 0.15, 0.25, 0.6 * alpha)
            ctx.set_line_width(3)
            ctx.move_to(sx, sy)
            ctx.curve_to(sx - 80, sy - 160 + 30 * math.sin(t * 4), ex + 120, ey - 120, ex, ey)
            ctx.stroke()

    # the boy, then the man
    bx = 540
    grow = ease_io(prog(t, T_GROW, T_GROW + 2.2))
    if t < T_GROW + 2.2:
        power = ease_out(prog(t, T_ABSORB + 0.8, T_ABSORB + 1.4))
        u = BOY_U
        def draw_boy():
            return draw_hero(ctx, BOY, bx, boy_y(u), u, t, max(0.15, power))
        hands = with_alpha(ctx, 1 - grow, draw_boy)
        # the diya and its flame
        if t < T_ABSORB + 1.0:
            hx, hy = bx, boy_y(u) - 0.6 * u - 8
            flame = 1.0
            if t > 14.5:
                flame = lerp(1.0, 0.25, ease_io(prog(t, 14.5, 16.5)))
            if t > T_ABSORB:
                flame = 0.25 + 0.8 * ease_out(prog(t, T_ABSORB, T_ABSORB + 0.4))
            diya(ctx, hx - 30, hy, flame * (1 - prog(t, T_ABSORB + 0.6, T_ABSORB + 1.0)), t)
    if grow > 0:
        u = lerp(BOY_U, ADULT_U, grow)
        power = 1.0
        def draw_adult():
            return draw_hero(ctx, AGNI, bx, boy_y(u), u, t, power)
        hands = with_alpha(ctx, grow, draw_adult)
        spear = ease_out(prog(t, T_SPEAR, T_SPEAR + 0.4))
        if spear > 0 and hands:
            kit.hero_fx_front(ctx, AGNI, t, t - T_SPEAR, bx, boy_y(u), u, spear, hands)

    # fire vortex: absorbing then exploding then growing
    if T_ABSORB < t < T_HERO + 0.5:
        cyv = boy_y(BOY_U) - 0.5 * BOY_U
        a = prog(t, T_ABSORB, T_ABSORB + 0.6) * (1 - prog(t, T_HERO - 0.5, T_HERO + 0.5))
        for ang, rad, sz, sp, ph in VORTEX:
            if t < T_BLAST:
                rr = rad * (1 - 0.8 * prog(t, T_ABSORB, T_BLAST)) + 20
                hh = 0
            else:
                rr = rad * (1.4 + 0.6 * math.sin(t + ph * 6)) + 120 * grow
                hh = ((ph + (t - T_BLAST) * 0.4 * sp) % 1.0) * 600 * (0.4 + grow)
            aa = ang + t * sp * 3
            px = bx + math.cos(aa) * rr
            py = cyv + math.sin(aa) * rr * 0.35 - hh
            glow(ctx, px, py, sz * 4, FIRE, 0.5 * a)
            ctx.set_source_rgba(*GOLD, a)
            ctx.arc(px, py, sz * 0.6, 0, TAU)
            ctx.fill()

    # blast
    if t >= T_BLAST:
        dt = t - T_BLAST
        cyb = boy_y(BOY_U) - 0.5 * BOY_U
        ring = ease_out(prog(dt, 0, 0.9))
        if ring < 1:
            ctx.set_source_rgba(*GOLD, 0.9 * (1 - ring))
            ctx.set_line_width(30 * (1 - ring) + 2)
            ctx.save()
            ctx.translate(bx, cyb)
            ctx.scale(1, 0.4)
            ctx.arc(0, 0, 60 + 1100 * ring, 0, TAU)
            ctx.restore()
            ctx.stroke()
        glow(ctx, bx, cyb, 900 * (0.3 + ring), FIRE, 0.7 * (1 - prog(dt, 0, 2.0)))

    # hero-moment embers
    if t >= T_HERO:
        for ex, ey, sp, sz, ph in EMB:
            life = (ey + (t - T_HERO) * sp / 500) % 1.0
            px = 540 + ex * 520 + 30 * math.sin(t * 2 + ph)
            py = GROUND - life * 1300
            glow(ctx, px, py, sz * 3, FIRE, 0.5 * (1 - life))
    ctx.restore()

    if T_BLAST <= t < T_BLAST + 0.12:
        ctx.set_source_rgba(1, 0.95, 0.85, 1)
        ctx.paint()
    elif t >= T_BLAST:
        ctx.set_source_rgba(1, 0.7, 0.3, 0.5 * math.exp(-(t - T_BLAST) * 3))
        ctx.paint()

    # narration
    lines = [
        (4.0, 6.8, ["The darkness took", "every light..."], (1, 1, 1)),
        (7.4, 10.6, ["...except one."], GOLD),
        (12.4, 16.6, ["He refused", "to let it go out."], (1, 1, 1)),
        (21.6, 25.4, ["The boy who saved", "the last flame..."], (1, 1, 1)),
    ]
    for t0, t1, ls, col in lines:
        y0 = 1600 if t0 > 20 else 380
        a = ease_io(prog(t, t0, t0 + 0.4)) * (1 - ease_io(prog(t, t1 - 0.4, t1)))
        for j, ln in enumerate(ls):
            text(ctx, ln, W / 2, y0 + j * 86, 68, col, a, FONT_BLACK if col == GOLD else FONT, 2,
                 glow_col=FIRE if col == GOLD else None)
    # name slam
    if t >= 27.0:
        p = ease_out(prog(t, 27.0, 27.15))
        sc = lerp(1.8, 1.0, p)
        a = 1 - ease_io(prog(t, T_END - 0.4, T_END))
        ctx.save()
        ctx.translate(W / 2, 1640)
        ctx.scale(sc, sc)
        text(ctx, "AGNI", 0, 0, 170, (1, 1, 1), p * a, FONT_BLACK, 16, glow_col=FIRE)
        ctx.restore()
        text(ctx, "LORD OF FIRE", W / 2, 1730, 44, GOLD, ease_io(prog(t, 27.3, 27.7)) * a, FONT, 12)
        text(ctx, "GUARDIAN  #1", W / 2, 1800, 30, (0.9, 0.85, 0.8), ease_io(prog(t, 28.2, 28.7)) * a, FONT, 8)
        if 27.0 <= t < 27.08:
            ctx.set_source_rgba(1, 1, 1, 0.7)
            ctx.paint()



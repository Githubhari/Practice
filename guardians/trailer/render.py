def speed_lines(ctx, cx, cy, t, a=0.5, col=(1, 1, 1)):
    k = int(t * 15)
    r = random.Random(k)
    for ang, inner, wdt in SPEEDLINES:
        if r.random() < 0.45:
            continue
        ang += r.uniform(-0.03, 0.03)
        r0 = inner * 1100 + r.uniform(-60, 60)
        r1 = 1500
        ctx.set_source_rgba(*col, a * r.uniform(0.3, 1))
        c, s = math.cos(ang), math.sin(ang)
        ctx.move_to(cx + c * r0, cy + s * r0)
        ctx.line_to(cx + c * r1 - s * wdt * 6, cy + s * r1 + c * wdt * 6)
        ctx.line_to(cx + c * r1 + s * wdt * 6, cy + s * r1 - c * wdt * 6)
        ctx.close_path()
        ctx.fill()



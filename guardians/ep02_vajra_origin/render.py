def slope_y(x):
    return 1750 - 0.6 * (x + 100) if x < 880 else 1174


KID_U = 120
TEMPLE_X = 990


def kid_x(t):
    s = ease_out(prog(t, T_STORM + 0.4, T_BELL_REACH)) * 0.55 + prog(t, T_STORM + 0.4, T_BELL_REACH) * 0.45
    return lerp(60, 880, s)


def zip_curve(p, vx, vy):
    """Spiral around the shadow, then back to the bell."""
    if p < 0.8:
        q = p / 0.8
        ang = q * TAU * 2.2 - math.pi / 2
        rad = 330 * (1 - 0.4 * q)
        return vx + math.cos(ang) * rad, vy + math.sin(ang) * rad * 0.7
    q = (p - 0.8) / 0.2
    ex, ey = vx + math.cos(TAU * 2.2 - math.pi / 2) * 200, vy + math.sin(TAU * 2.2 - math.pi / 2) * 140
    return lerp(ex, 880, ease_io(q)), lerp(ey, slope_y(880) - 0.6 * KID_U, ease_io(q))


def shadow_state(t):
    kx = kid_x(min(t, T_BELL_REACH))
    gap = lerp(520, 190, ease_io(prog(t, T_STORM + 0.5, 17.6)))
    vx = kx - gap
    return vx, slope_y(vx) - 330



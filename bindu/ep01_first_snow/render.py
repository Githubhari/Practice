SR = 44100


def note(n):
    return 440 * 2 ** ((n - 69) / 12)


def make_audio(path):
    N = int(SR * DUR)
    out = np.zeros(N)
    rng_a = np.random.default_rng(3)

    def add(sig, start, gain=1.0):
        s = int(start * SR)
        if s < 0:
            sig, s = sig[-s:], 0
        e = min(N, s + len(sig))
        if e > s:
            out[s:e] += gain * sig[:e - s]

    def tl(d):
        return np.arange(int(d * SR)) / SR

    def bell(n, dur=1.6):
        tt = tl(dur)
        f = note(n)
        s = (np.sin(TAU * f * tt) + 0.45 * np.sin(TAU * f * 2 * tt) * np.exp(-tt * 3)
             + 0.25 * np.sin(TAU * f * 3.01 * tt) * np.exp(-tt * 6)
             + 0.12 * np.sin(TAU * f * 4.2 * tt) * np.exp(-tt * 9))
        return s * np.exp(-tt * 2.6) * np.minimum(1, tt / 0.003)

    def pluck(n, dur=0.45):
        tt = tl(dur)
        f = note(n)
        return (np.sin(TAU * f * tt) + 0.3 * np.sin(TAU * 2 * f * tt)) * np.exp(-tt * 7) * np.minimum(1, tt / 0.004)

    def pad(notes, dur):
        tt = tl(dur + 1.0)
        s = np.zeros(len(tt))
        for n in notes:
            f = note(n)
            for det in (1.0, 1.005, 0.996):
                s += np.sin(TAU * f * det * tt) + 0.2 * np.sin(TAU * 2 * f * det * tt)
        env = np.minimum(1, tt / 0.4) * np.clip((dur + 1.0 - tt) / 1.0, 0, 1)
        return s * env / (3 * len(notes))

    def noise(d):
        return rng_a.standard_normal(int(d * SR))

    def lowpass(x, k):
        return np.convolve(x, np.ones(k) / k, mode="same")

    def jingle(d=0.18):
        n = noise(d)
        hp = n - lowpass(n, 4)
        tt = tl(d)
        am = 0.6 + 0.4 * np.sin(TAU * 38 * tt)
        return hp * np.exp(-tt * 26) * am

    def sweep(f0, f1, d, decay=8):
        tt = tl(d)
        f = np.linspace(f0, f1, len(tt))
        return np.sin(TAU * np.cumsum(f) / SR) * np.exp(-tt * decay)

    B0 = 1.0                                          # beat grid origin

    def bt(b):
        return B0 + b * BEAT

    chords = {"C": [60, 64, 67], "F": [60, 65, 69], "G": [59, 62, 67], "G7": [59, 62, 65, 67]}
    bass = {"C": (48, 55), "F": (53, 48), "G": (55, 50), "G7": (55, 50)}
    # bar plan: (start beat, chord)
    bars = [(4, "C"), (8, "F"), (12, "G7")]
    bars += [(16 + 4 * k, c) for k, c in enumerate("C C C C F C G G".split())]
    bars += [(48 + 4 * k, c) for k, c in enumerate("F C G C".split())]
    for b, c in bars:
        add(pad(chords[c], 4 * BEAT), bt(b), 0.10 if b < 48 else 0.14)
        r, fifth = bass[c]
        for k in range(4):
            add(pluck(r if k % 2 == 0 else fifth, 0.4), bt(b + k), 0.22)
    add(pad(chords["C"] + [72], 3.0), bt(64), 0.16)
    add(pluck(48, 1.2), bt(64), 0.25)

    # sleigh bells on every beat, accents on 2 & 4
    for k in range(4, 64):
        add(jingle(), bt(k), 0.10 if k % 2 else 0.06)
        if k >= 48:
            add(jingle(0.1), bt(k + 0.5), 0.05)

    # melody: Jingle Bells chorus (public domain)
    A = [(76, 1), (76, 1), (76, 2), (76, 1), (76, 1), (76, 2), (76, 1), (79, 1), (72, 1.5), (74, .5),
         (76, 4), (77, 1), (77, 1), (77, 1.5), (77, .5), (77, 1), (76, 1), (76, 1), (76, .5), (76, .5),
         (76, 1), (74, 1), (74, 1), (76, 1), (74, 2), (79, 2)]
    Btail = [(77, 1), (77, 1), (77, 1), (77, 1), (77, 1), (76, 1), (76, 1), (76, .5), (76, .5),
             (79, 1), (79, 1), (77, 1), (74, 1), (72, 4)]
    b = 16
    for n, d in A:
        add(bell(n, max(0.8, d * BEAT * 2)), bt(b), 0.2)
        b += d
    b = 48
    for n, d in Btail:
        add(bell(n, max(0.8, d * BEAT * 2)), bt(b), 0.22)
        add(bell(n + 12, max(0.6, d * BEAT * 1.5)), bt(b), 0.08)
        b += d

    # intro twinkles + wind
    for k, n in enumerate([84, 88, 91, 96, 91, 88]):
        add(bell(n, 1.5), 0.3 + k * 0.45, 0.06)
    wind = lowpass(noise(DUR), 60)
    wind *= 0.6 + 0.4 * np.sin(TAU * 0.13 * np.arange(N) / SR)
    add(wind * 0.5, 0)

    # ---- SFX
    add(sweep(700, 1100, 0.18, 18), 1.0, 0.25)                  # boop
    inh = lowpass(noise(0.5), 8) * np.linspace(0, 1, int(0.5 * SR)) ** 2
    add(inh, 1.45, 0.25)                                       # inhale
    ach = lowpass(noise(0.35), 3) * np.exp(-tl(0.35) * 9)
    add(ach, 2.0, 0.45)
    add(sweep(620, 220, 0.3, 6), 2.0, 0.22)                    # "choo"
    sw = lowpass(noise(1.4), 25) * np.sin(np.linspace(0, math.pi, int(1.4 * SR)))
    add(sw, 2.05, 0.6)                                          # camera whoosh
    for t0, t1, x0, x1, h in HOPS:
        if t0 < 25:
            add(sweep(300 + h, 520 + h * 2, 0.12, 30), t0 + 0.01, 0.12)
            add(lowpass(noise(0.08), 4) * np.exp(-tl(0.08) * 50), t1, 0.12)
    add(sweep(900, 1500, 0.12, 25), 5.75, 0.2)                  # gulp
    add(bell(96, 1.0), 5.8, 0.06)
    tt = tl(0.6)
    add(np.sin(TAU * 180 * tt) * (0.5 + 0.5 * np.sin(TAU * 28 * tt)) * np.exp(-tt * 4), 6.0, 0.12)
    for k in range(int((PUSH_T1 - PUSH_T0) / 0.13)):            # crunchy rolling
        add(lowpass(noise(0.07), 2) * np.exp(-tl(0.07) * 60), PUSH_T0 + k * 0.13, 0.12)
    for t0, t1, r, ty in THROWS:
        add(sweep(400, 900, 0.3, 6), t0, 0.08)
        tt = tl(0.3)
        add(np.sin(TAU * 110 * tt) * np.exp(-tt * 14) + 0.4 * lowpass(noise(0.3), 5) * np.exp(-tt * 20), t1, 0.35)
    for k, tp in enumerate((14.2, 14.3, 14.6, 15.0, 15.4, 15.8)):
        add(sweep(1400 - k * 60, 500, 0.09, 30), tp, 0.18)
    for k, n in enumerate((79, 84, 88)):                        # orb chime
        add(bell(n + 12, 1.5), ORB_T0 + k * 0.08, 0.08)
    sw = lowpass(noise(0.8), 10) * np.sin(np.linspace(0, math.pi, int(0.8 * SR)))
    add(sw, ORB_FLY, 0.35)
    scale = [72, 74, 76, 77, 79, 81, 83, 84, 86, 88, 89, 91, 93, 95, 96, 98, 100, 101]
    for k in range(N_LIGHTS):                                   # lights
        add(bell(scale[k], 0.9), LIGHT_T0 + k * LIGHT_DT, 0.07)
    for n in (84, 88, 91, 96, 100):                             # star
        add(bell(n, 2.5), STAR_T, 0.07)
    add(lowpass(noise(1.2), 2) * np.exp(-tl(1.2) * 4) * 0.5, STAR_T, 0.25)
    add(sweep(350, 1000, 0.4, 7), STAR_T + 0.05, 0.15)          # joy boing
    add(sweep(700, 1100, 0.18, 18), 34.0, 0.25)                 # final boop

    t = np.arange(N) / SR
    out *= np.clip((DUR - t) / 0.6, 0, 1)
    out = np.tanh(out * 1.3)
    out /= np.max(np.abs(out)) * 1.1
    dl = int(0.012 * SR)
    left = out
    right = np.concatenate([np.zeros(dl), out[:-dl]]) * 0.85 + out * 0.15
    st = (np.stack([left, right], 1) * 32767).astype(np.int16)
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(st.tobytes())



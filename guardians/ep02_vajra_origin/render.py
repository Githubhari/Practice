def rain_time(t):
    if t < T_FREEZE:
        return t
    if t < T_UNFREEZE:
        return T_FREEZE
    return t - (T_UNFREEZE - T_FREEZE)


def frozen(t):
    return ease_out(prog(t, T_FREEZE, T_FREEZE + 0.3)) * (1 - ease_io(prog(t, T_UNFREEZE - 0.3, T_UNFREEZE)))


def draw_rain(ctx, t, a=0.5):
    rt = rain_time(t)
    fz = frozen(t)
    for x0, y0, sp, ln, wd in RAIN:
        y = (y0 + sp * rt) % (H + 200) - 100
        x = (x0 - 0.25 * sp * rt) % (W + 400) - 200
        if fz > 0.5:
            glow(ctx, x, y, 7, WHITE, 0.5 * a)
            ctx.set_source_rgba(1, 1, 1, a)
            ctx.arc(x, y, wd, 0, TAU)
            ctx.fill()
        else:
            ctx.set_source_rgba(0.75, 0.85, 1, a * 0.7)
            ctx.set_line_width(wd)
            ctx.move_to(x, y)
            ctx.line_to(x - ln * 0.25, y + ln)
            ctx.stroke()


def sky_flash(t):
    f = sum(math.exp(-(t - ft) * 7) for ft in STORM_FLASHES if t >= ft)
    if t >= T_STRIKE:
        f += 2 * math.exp(-(t - T_STRIKE) * 4)
    if t >= T_HERO:
        f += 1.5 * math.exp(-(t - T_HERO) * 5)
    return min(f, 1.5) * (1 - frozen(t))



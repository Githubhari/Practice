RACE_G = 1400


def vajra_kid_x(t):
    s = t - T_RACE - 0.2
    if s <= 0:
        return -180
    v, t1, t2 = 230, 2.7, 3.8
    if s < t1:
        return -180 + v * s
    if s < t2:
        d = s - t1
        return -180 + v * t1 + v * d - 0.5 * v / (t2 - t1) * d * d
    return -180 + v * t1 + 0.5 * v * (t2 - t1)



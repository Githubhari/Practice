def post(surf, t, impact):
    buf = surf.get_data()
    arr = np.ndarray((H, W, 4), np.uint8, buf).astype(np.int16)
    if impact:
        lum = arr[..., :3].mean(axis=2)
        bw = np.where(lum > 60, 0, 255) if impact == 1 else np.where(lum > 60, 255, 0)
        arr[..., 0] = bw * 0.35
        arr[..., 1] = bw * 0.35
        arr[..., 2] = bw
        if impact == 2:
            arr[..., 2] = np.where(lum > 60, 255, 40)
            arr[..., 1] = np.where(lum > 60, 240, 0)
            arr[..., 0] = np.where(lum > 60, 240, 0)
    rng = np.random.default_rng(int(t * FPS))
    grain = rng.integers(-9, 10, (H // 2, W // 2), dtype=np.int16).repeat(2, 0).repeat(2, 1)
    arr[..., :3] += grain[..., None]
    np.clip(arr, 0, 255, out=arr)
    np.ndarray((H, W, 4), np.uint8, buf)[:] = arr.astype(np.uint8)


def draw_frame(i):
    t = i / FPS
    surf = cairo.ImageSurface(cairo.FORMAT_RGB24, W, H)
    ctx = cairo.Context(surf)
    dx, dy = shake(t)
    ctx.translate(dx, dy)
    ctx.translate(W / 2, H / 2)
    ctx.scale(1.04, 1.04)          # overscan so shake never shows edges
    ctx.translate(-W / 2, -H / 2)
    if t < T_VILLAIN:
        scene_darkness(ctx, t)
    elif t < T_HEROES:
        scene_villain(ctx, t)
    elif t < T_LINEUP:
        scene_hero(ctx, t, int((t - T_HEROES) / HERO_LEN))
    elif t < T_CLASH:
        scene_lineup(ctx, t)
    elif t < T_WHITE:
        scene_clash(ctx, t)
    elif t < T_BINDU:
        scene_white(ctx, t)
    elif t < T_TITLE:
        scene_bindu(ctx, t)
    else:
        scene_title(ctx, t)
    ctx.identity_matrix()
    v = cairo.RadialGradient(W / 2, H / 2, H * 0.3, W / 2, H / 2, H * 0.72)
    v.add_color_stop_rgba(0, 0, 0, 0, 0)
    v.add_color_stop_rgba(1, 0, 0, 0, 0.6)
    ctx.set_source(v)
    ctx.paint()
    if t > DUR - 0.8:
        ctx.set_source_rgba(0, 0, 0, prog(t, DUR - 0.8, DUR))
        ctx.paint()
    surf.flush()
    impact = 0
    if T_IMPACT <= t < T_WHITE:
        impact = 1 + (int((t - T_IMPACT) * FPS) // 3) % 2
    post(surf, t, impact)
    surf.mark_dirty()
    surf.write_to_png(os.path.join(FRAMES, f"f{i:04d}.png"))



# ------------------------------------------------------------------ helpers
def clamp(x, a=0.0, b=1.0):
    return max(a, min(b, x))


def prog(t, t0, t1):
    return clamp((t - t0) / (t1 - t0))


def ease_io(x):
    return x * x * (3 - 2 * x)


def ease_out(x):
    return 1 - (1 - x) ** 3


def ease_back(x):
    c = 1.9
    return 1 + (c + 1) * (x - 1) ** 3 + c * (x - 1) ** 2


def lerp(a, b, x):
    return a + (b - a) * x


def lerp_col(c1, c2, x):
    return tuple(lerp(a, b, x) for a, b in zip(c1, c2))


def hexc(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def glow(ctx, x, y, r, col, a=1.0):
    if r <= 0 or a <= 0:
        return
    g = cairo.RadialGradient(x, y, 0, x, y, r)
    g.add_color_stop_rgba(0, *col, a)
    g.add_color_stop_rgba(0.3, *col, a * 0.35)
    g.add_color_stop_rgba(1, *col, 0)
    ctx.set_source(g)
    ctx.arc(x, y, r, 0, TAU)
    ctx.fill()


def ellipse(ctx, x, y, rx, ry):
    ctx.save()
    ctx.translate(x, y)
    ctx.scale(rx, ry)
    ctx.arc(0, 0, 1, 0, TAU)
    ctx.restore()


def snowflake(ctx, x, y, s, rot, a=1.0):
    """Detailed six-armed snowflake."""
    ctx.save()
    ctx.translate(x, y)
    ctx.rotate(rot)
    glow(ctx, 0, 0, s * 2.2, (0.85, 0.93, 1), 0.45 * a)
    ctx.set_source_rgba(1, 1, 1, a)
    ctx.set_line_width(max(1.0, s * 0.16))
    ctx.set_line_cap(cairo.LINE_CAP_ROUND)
    for k in range(6):
        ang = k * TAU / 6
        c, sn = math.cos(ang), math.sin(ang)
        ctx.move_to(0, 0)
        ctx.line_to(c * s, sn * s)
        for d in (0.45, 0.7):
            bx, by = c * s * d, sn * s * d
            for side in (-1, 1):
                a2 = ang + side * 0.8
                ctx.move_to(bx, by)
                ctx.line_to(bx + math.cos(a2) * s * 0.3, by + math.sin(a2) * s * 0.3)
    ctx.stroke()
    ctx.restore()


# ------------------------------------------------------------------ timeline
BEAT = 0.5          # 120 bpm
PUSH_T0, PUSH_T1 = 9.0, 12.0
BALL_X0, BALL_X1, BALL_R0, BALL_R1 = 230, 340, 18, 85
SNOWMAN_X = BALL_X1
MID_R, HEAD_R = 60, 42
BASE_Y = G - 78
MID_Y = BASE_Y - BALL_R1 - MID_R + 22
HEAD_Y = MID_Y - MID_R - HEAD_R + 14
THROWS = [(12.0, 12.6, MID_R, MID_Y), (13.4, 14.0, HEAD_R, HEAD_Y)]
TREE_X = 860
ORB_T0, ORB_FLY, ORB_IN = 19.0, 19.6, 20.4
N_LIGHTS = 18
LIGHT_T0, LIGHT_DT = 20.5, 0.14
STAR_T = LIGHT_T0 + N_LIGHTS * LIGHT_DT + 0.1      # ~23.1


def ball_state(t):
    p = ease_io(prog(t, PUSH_T0, PUSH_T1))
    return lerp(BALL_X0, BALL_X1, p), lerp(BALL_R0, BALL_R1, p)


def push_x(t):
    bx, br = ball_state(t)
    return bx - br - 0.9 * R


PX0, PX1 = push_x(PUSH_T0), push_x(PUSH_T1)

# (t0, t1, x0, x1, height)
HOPS = [
    (3.5, 4.0, 540, 600, 60), (4.0, 4.5, 600, 660, 60), (4.5, 5.0, 660, 620, 40),
    (5.5, 6.0, 620, 620, 95),
    (7.0, 7.5, 620, 480, 60), (7.5, 8.0, 480, 340, 60), (8.0, 8.5, 340, 220, 55),
    (8.5, 9.0, 220, PX0, 35),
    (12.0, 12.6, PX1, PX1, 70), (13.4, 14.0, PX1, PX1, 70),
    (16.2, 16.7, PX1, PX1, 85),
    (17.5, 18.1, PX1, 420, 70), (18.1, 18.7, 420, 640, 70),
    (STAR_T, STAR_T + 0.7, 640, 640, 130),
    (24.0, 24.5, 640, 590, 45), (24.5, 25.0, 590, 540, 45),
]
HOPS += [(25.0 + k * BEAT, 25.0 + (k + 1) * BEAT - 0.02, 540, 540, 34) for k in range(7)]
HOPS += [(28.5 + k * 1.0, 28.5 + k * 1.0 + BEAT, 540, 540, 24) for k in range(4)]


def bindu_body(t):
    """x, lift, sx, sy, lean for Bindu."""
    x, lift, sy, lean = 540.0, 0.0, 1.0, 0.0
    last_end = None
    for t0, t1, x0, x1, h in HOPS:
        if t0 <= t < t1:
            p = (t - t0) / (t1 - t0)
            x = lerp(x0, x1, ease_io(p) * 0.3 + p * 0.7)
            lift = h * math.sin(math.pi * p)
            contact = clamp(1 - min(p, 1 - p) * 7)
            sy = 1 + 0.13 * math.sin(math.pi * p) - 0.2 * contact
            return x, lift, 1 / math.sqrt(sy), sy, 0.0
        if t >= t1:
            last_end = (t1, x1)
    if last_end:
        te, x = last_end
        land = prog(t, te, te + 0.25)
        sy = 1 - 0.16 * math.sin(math.pi * land) * (1 - land)
    if PUSH_T0 <= t < PUSH_T1:
        x = push_x(t)
        lean = 0.14
        sy = 1 - 0.05 * abs(math.sin(t * 9))
    # inhale before the sneeze, then the sneeze
    if 1.45 <= t < 2.0:
        sy = 1 + 0.14 * ease_io(prog(t, 1.45, 1.95))
        lean = -0.12 * prog(t, 1.45, 1.95)
    elif 2.0 <= t < 2.45:
        p = prog(t, 2.0, 2.45)
        sy = 1 - 0.22 * math.sin(math.pi * p) * (1 - p) * 1.5
        lean = 0.18 * (1 - p) * math.sin(p * 9)
    # happy shiver after catching the snowflake
    if 6.0 <= t < 6.6:
        x += 3.5 * math.sin(t * 90) * (1 - prog(t, 6.0, 6.6))
    sy += 0.015 * math.sin(t * 3.5)
    return x, lift, 1 / math.sqrt(max(sy, 0.5)), sy, lean


def mouth_world(t):
    x, lift, sx, sy, _ = bindu_body(t)
    return x, G - lift - (R * 0.95) * sy


def orb_pos(t):
    hx, hy = 640, G - 2 * R - 75
    if t < ORB_FLY:
        return hx, hy
    p = ease_io(prog(t, ORB_FLY, ORB_IN))
    ex, ey = TREE_X, G - 90
    cx, cy = (hx + ex) / 2, hy - 220
    return ((1 - p) ** 2 * hx + 2 * (1 - p) * p * cx + p * p * ex,
            (1 - p) ** 2 * hy + 2 * (1 - p) * p * cy + p * p * ey)


def throw_pos(t, t0, t1, ty):
    p = prog(t, t0, t1)
    sx, sy = PX1, G - 2 * R - 30
    return lerp(sx, SNOWMAN_X, p), lerp(sy, ty, p) - 180 * math.sin(math.pi * p)


# hero snowflakes: (t_start, t_land, start_xy, target function)
def nose_target(t):
    x, lift, sx, sy, _ = bindu_body(t)
    return x, G - lift - (R * 1.02) * sy


def hero_flakes(t):
    out = []
    # opening flake lands on the nose at 1.0, flies off with the sneeze at 2.0
    for (ts, tl, toff) in ((0.0, 1.0, 2.0), (33.0, 34.0, 99.0)):
        if ts <= t < toff + 0.8:
            tx, ty = nose_target(min(t, tl))
            if t < tl:
                p = prog(t, ts, tl)
                fx = tx + 30 * math.sin(p * 5) * (1 - p)
                fy = lerp(ty - 260, ty, ease_out(p) * 0.5 + p * 0.5)
                rot = t * 1.5
            elif t < toff:
                fx, fy, rot = tx, ty, tl * 1.5
            else:
                p = t - toff
                fx, fy, rot = tx + 420 * p, ty - 300 * p + 200 * p * p, t * 12
            out.append((fx, fy, 11, rot, 1.0))
    # flake caught in the mouth at the top of the hop
    if 4.6 <= t < 5.75:
        tx, ty = mouth_world(5.75)
        p = prog(t, 4.6, 5.75)
        out.append((tx + 25 * math.sin(p * 6) * (1 - p), lerp(ty - 380, ty, p), 9, t * 2, 1.0))
    return out


# ------------------------------------------------------------------ camera
CLOSE = (540, G - R - 40, 3.0)
CX_KEYS = [(0, 540), (4.0, 540), (5.0, 610), (7.0, 610), (9.0, 420), (17.0, 420),
           (19.0, 650), (24.0, 650), (25.5, 560), (DUR, 560)]
WIDE_Z, WIDE_CY = 1.3, 1140
TREE_Z, TREE_CY = 1.55, 1130


def cam_x(t):
    for (t0, x0), (t1, x1) in zip(CX_KEYS, CX_KEYS[1:]):
        if t0 <= t <= t1:
            return lerp(x0, x1, ease_io(prog(t, t0, t1)))
    return CX_KEYS[-1][1]


def camera(t):
    def mix(a, b, p):
        return tuple(lerp(u, v, p) for u, v in zip(a, b))
    wide = (cam_x(t), WIDE_CY, WIDE_Z)
    if t < 2.05:
        c = CLOSE
        return (c[0], c[1] + 6 * math.sin(t * 2), c[2] + 0.03 * t)
    if t < 3.6:
        return mix((CLOSE[0], CLOSE[1], CLOSE[2] + 0.06), wide, ease_io(prog(t, 2.05, 3.6)))
    tree = (cam_x(t), TREE_CY, TREE_Z)
    if t < 17.0:
        return wide
    if t < 23.8:
        return mix(wide, tree, ease_io(prog(t, 17.0, 19.5)))
    if t < 32.4:
        return mix(tree, wide, ease_io(prog(t, 23.8, 25.2)))
    return mix(wide, CLOSE, ease_io(prog(t, 32.4, 33.4)))



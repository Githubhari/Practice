def pose_bottom(name):
    return max(l[-1][1] for l in kit.POSES[name]["legs"])


def draw_figure(ctx, key, pose, h, x, ground_y, u, t, power, bob=0.0):
    kit.POSES[key] = pose
    y = ground_y - pose_bottom(key) * u - bob * u
    return draw_hero(ctx, dict(h, pose=key), x, y, u, t, power)


def draw_posed(ctx, name, h, x, ground_y, u, t, power):
    return draw_hero(ctx, dict(h, pose=name), x, ground_y - pose_bottom(name) * u, u, t, power)



def sea(ctx, y0, layers, t, poison=0.0, glow_a=0.0, speed=1.0, amp_k=1.0):
    """Layered ocean from horizon y0 downward."""
    calm = [hexc("#2a6f97"), hexc("#1f5f86"), hexc("#174d70"), hexc("#103c59")]
    dark = [hexc("#1a0a18"), hexc("#140612"), hexc("#10040e"), hexc("#0b020a")]
    glowc = [hexc("#127a7a"), hexc("#0d6a6c"), hexc("#0a585c"), hexc("#07464c")]
    for k in range(layers):
        y = y0 + k * 110
        amp = (8 + k * 14) * amp_k
        fr = 0.012 - k * 0.002
        col = calm[k % 4]
        col = tuple(lerp(a, b, poison) for a, b in zip(col, dark[k % 4]))
        col = tuple(lerp(a, b, glow_a) for a, b in zip(col, glowc[k % 4]))
        ctx.set_source_rgb(*col)
        pts = []
        for x in range(-300, W + 320, 16):
            yy = y + amp * math.sin(x * fr + t * speed * (1 + 0.3 * k) + k) + amp * 0.5 * math.sin(
                x * fr * 2.3 - t * speed * 1.3 + k * 2)
            pts.append((x, yy))
        ctx.move_to(-300, H + 400)
        for p in pts:
            ctx.line_to(*p)
        ctx.line_to(W + 320, H + 400)
        ctx.close_path()
        ctx.fill()
        foam = (1, 0.3, 0.35) if poison > 0.5 else (AQUA if glow_a > 0.5 else (0.85, 0.95, 1))
        ctx.set_source_rgba(*foam, 0.35 + 0.2 * k / layers)
        ctx.set_line_width(2 + k)
        ctx.move_to(*pts[0])
        for p in pts[1:]:
            ctx.line_to(*p)
        ctx.stroke()


def boat(ctx, x, y, s, t, ph=0.0, roll=0.08, waving=False):
    ctx.save()
    ctx.translate(x, y)
    ctx.rotate(roll * math.sin(t * 2.2 + ph))
    ctx.scale(s, s)
    ctx.set_source_rgb(0.05, 0.04, 0.05)
    ctx.move_to(-70, -10)
    ctx.line_to(70, -10)
    ctx.line_to(50, 14)
    ctx.line_to(-50, 14)
    ctx.close_path()
    ctx.fill()
    ctx.rectangle(-3, -120, 6, 112)
    ctx.fill()
    ctx.move_to(4, -116)
    ctx.line_to(60, -22)
    ctx.line_to(4, -22)
    ctx.close_path()
    ctx.fill()
    # fisherman
    ctx.arc(-34, -46, 8, 0, TAU)
    ctx.fill()
    ctx.rectangle(-40, -38, 12, 28)
    ctx.fill()
    if waving:
        ctx.set_line_width(4)
        ctx.set_line_cap(cairo.LINE_CAP_ROUND)
        a = -2.4 + 0.5 * math.sin(t * 8)
        ctx.move_to(-38, -34)
        ctx.line_to(-38 + 26 * math.cos(a), -34 + 26 * math.sin(a))
        ctx.stroke()
    ctx.restore()


def draw_rain(ctx, t, a=0.4):
    for x0, y0, sp, ln, wd in RAIN:
        y = (y0 + sp * t) % (H + 200) - 100
        x = (x0 - 0.25 * sp * t) % (W + 400) - 200
        ctx.set_source_rgba(0.75, 0.85, 1, a * 0.7)
        ctx.set_line_width(wd)
        ctx.move_to(x, y)
        ctx.line_to(x - ln * 0.25, y + ln)
        ctx.stroke()


def big_wave(ctx, x0, crest_y, width, t, col, foam_col, curl=1.0):
    """A tall curling wave whose face spans from x0 to x0+width."""
    base = H + 200
    ctx.move_to(x0 - 200, base)
    ctx.curve_to(x0, base - 300, x0 + width * 0.25, crest_y + 300, x0 + width * 0.55, crest_y)
    ctx.curve_to(x0 + width * 0.75, crest_y - 60 * curl, x0 + width * 0.95, crest_y + 40,
                 x0 + width * 0.85, crest_y + 130 * curl)
    ctx.curve_to(x0 + width * 0.95, crest_y + 160, x0 + width, crest_y + 300, x0 + width + 400, base)
    ctx.close_path()
    g = cairo.LinearGradient(0, crest_y, 0, base)
    g.add_color_stop_rgb(0, *col)
    g.add_color_stop_rgb(1, *(c * 0.4 for c in col))
    ctx.set_source(g)
    ctx.fill()
    ctx.set_source_rgba(*foam_col, 0.8)
    ctx.set_line_width(7)
    ctx.move_to(x0 + width * 0.3, crest_y + 140)
    ctx.curve_to(x0 + width * 0.45, crest_y + 10, x0 + width * 0.6, crest_y - 20, x0 + width * 0.8, crest_y + 30)
    ctx.stroke()



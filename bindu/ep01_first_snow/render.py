    surf = cairo.ImageSurface(cairo.FORMAT_RGB24, W, H)
    ctx = cairo.Context(surf)
    warm = ease_io(prog(t, STAR_T, STAR_T + 1.2))

    cx, cy, z = camera(t)
    cam = cairo.Matrix()
    cam.translate(W / 2, H / 2)
    cam.scale(z, z)
    cam.translate(-cx, -cy)

    ctx.set_matrix(cam)
    draw_background(ctx, t, warm)
    ctx.identity_matrix()
    draw_snowfall(ctx, t, (0,))
    ctx.set_matrix(cam)

    # warm light pool from the lit tree
    if warm > 0:
        ctx.save()
        ctx.translate(TREE_X, G)
        ctx.scale(1, 0.3)
        glow(ctx, 0, 0, 520, hexc("#ffb36b"), 0.45 * warm)
        ctx.restore()
    draw_tree(ctx, t)
    draw_snowman(ctx, t)
    draw_bindu(ctx, t)
    draw_orb(ctx, t)
    for fx, fy, s, rot, a in hero_flakes(t):
        snowflake(ctx, fx, fy, s, rot, a)

    # star burst
    if t >= STAR_T:
        dt = t - STAR_T
        sx, sy = TREE_X, G - 440
        if dt < 1.6:
            for ang, spd, r, col in SPARKS:
                d = (1 - math.exp(-2.5 * dt)) / 2.5
                px = sx + math.cos(ang) * spd * d
                py = sy + math.sin(ang) * spd * d + 60 * dt * dt
                al = 1 - dt / 1.6
                glow(ctx, px, py, r * 4, col, al * 0.6)
                ctx.set_source_rgba(*col, al)
                ctx.arc(px, py, r, 0, TAU)
                ctx.fill()
        ring = ease_out(prog(dt, 0, 0.7))
        if ring < 1:
            ctx.set_source_rgba(1, 0.95, 0.8, 0.8 * (1 - ring))
            ctx.set_line_width(7 * (1 - ring) + 1)
            ctx.arc(sx, sy, 30 + 300 * ring, 0, TAU)
            ctx.stroke()

    ctx.identity_matrix()
    draw_snowfall(ctx, t, (1, 2))

    # warm grade + flash
    if warm > 0:
        ctx.set_source_rgba(1, 0.6, 0.3, 0.07 * warm)
        ctx.paint()
    if t >= STAR_T:
        ctx.set_source_rgba(1, 0.95, 0.85, math.exp(-(t - STAR_T) * 6) * 0.4)
        ctx.paint()

    # hook caption (readable with sound off)
    a = ease_io(prog(t, 0.1, 0.4)) * (1 - ease_io(prog(t, 3.0, 3.5)))
    if a > 0:
        ctx.set_source_rgba(0.02, 0.05, 0.15, 0.45 * a)
        x0, y0, w, h, r = 110, 220, W - 220, 190, 40
        ctx.new_sub_path()
        ctx.arc(x0 + w - r, y0 + r, r, -math.pi / 2, 0)
        ctx.arc(x0 + w - r, y0 + h - r, r, 0, math.pi / 2)
        ctx.arc(x0 + r, y0 + h - r, r, math.pi / 2, math.pi)
        ctx.arc(x0 + r, y0 + r, r, math.pi, 1.5 * math.pi)
        ctx.close_path()
        ctx.fill()
        text_center(ctx, "Bindu sees snow", 300, 66, (1, 1, 1), a=a)
        text_center(ctx, "for the very first time...", 375, 50, (0.85, 0.92, 1),
                    cairo.FONT_WEIGHT_NORMAL, a=a)

    # title card
    a = ease_io(prog(t, 28.6, 29.4)) * (1 - ease_io(prog(t, 31.9, 32.5)))
    if a > 0:
        rise = (1 - ease_io(prog(t, 28.6, 29.4))) * 24
        text_center(ctx, "E P I S O D E   1", 470 + rise, 32, (0.8, 0.88, 1),
                    cairo.FONT_WEIGHT_NORMAL, a=a)
        text_center(ctx, "Bindu's First Snow", 575 + rise, 92, (1, 0.98, 0.93), a=a,
                    glow_col=(1, 0.8, 0.4))
        b = ease_io(prog(t, 29.2, 30.0)) * (1 - ease_io(prog(t, 31.9, 32.5)))
        text_center(ctx, "Merry Christmas!", 670 + rise, 60, (1, 0.82, 0.4), a=b,
                    glow_col=(1, 0.5, 0.3))

    # vignette
    v = cairo.RadialGradient(W / 2, H / 2, H * 0.3, W / 2, H / 2, H * 0.75)
    v.add_color_stop_rgba(0, 0, 0, 0, 0)
    v.add_color_stop_rgba(1, 0.0, 0.02, 0.08, 0.5)
    ctx.set_source(v)
    ctx.paint()

    surf.write_to_png(os.path.join(FRAMES, f"f{i:04d}.png"))



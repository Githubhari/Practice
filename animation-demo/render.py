"""The Little Light - a 15 second procedural animation demo.

Everything (art, animation, VFX, music, edit) is generated by this script.
Usage: python render.py   ->  writes the_little_light.mp4
"""
import math
import os
import random
import subprocess
import wave
from multiprocessing import Pool

import cairo
import numpy as np

W, H, FPS, DUR = 1280, 720, 30, 15.0
NFRAMES = int(FPS * DUR)
GROUND = 600
HERE = os.path.dirname(os.path.abspath(__file__))
FRAMES = os.path.join(HERE, "frames")


# ---------------------------------------------------------------- helpers
def clamp(x, a=0.0, b=1.0):
    return max(a, min(b, x))


def prog(t, t0, t1):
    return clamp((t - t0) / (t1 - t0))


def ease_io(x):
    return x * x * (3 - 2 * x)


def ease_out(x):
    return 1 - (1 - x) ** 3


def ease_back(x):
    c = 1.7
    return 1 + (c + 1) * (x - 1) ** 3 + c * (x - 1) ** 2


def lerp(a, b, x):
    return a + (b - a) * x


def lerp_col(c1, c2, x):
    return tuple(lerp(a, b, x) for a, b in zip(c1, c2))


def hexc(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def glow(ctx, x, y, r, col, a=1.0):
    g = cairo.RadialGradient(x, y, 0, x, y, r)
    g.add_color_stop_rgba(0, *col, a)
    g.add_color_stop_rgba(0.35, *col, a * 0.35)
    g.add_color_stop_rgba(1, *col, 0)
    ctx.set_source(g)
    ctx.arc(x, y, r, 0, 2 * math.pi)
    ctx.fill()


# ---------------------------------------------------------------- static data
rng = random.Random(7)
STARS = [(rng.uniform(0, W + 200), rng.uniform(0, 430), rng.uniform(0.6, 2.2),
          rng.uniform(1.0, 3.5), rng.uniform(0, 6.28)) for _ in range(170)]
BURST = [(rng.uniform(0, 6.283), rng.uniform(60, 330), rng.uniform(1.5, 4),
          rng.choice([hexc("#fff3b0"), hexc("#ffd166"), hexc("#ff9fb2"), hexc("#a0e7ff")]))
         for _ in range(110)]
FIREFLIES = [(rng.uniform(80, W - 80), rng.uniform(560, 700), rng.uniform(0, 0.9),
              rng.uniform(25, 70), rng.uniform(0, 6.28)) for _ in range(34)]
GRASS = [(x, rng.uniform(14, 34), rng.uniform(-6, 6)) for x in range(-60, W + 120, 9)]

HOP_T0, HOP_T1, HOPS = 3.0, 6.5, 5
LAUNCH, BURST_T = 7.6, 10.0


def hill_y(x, base, amp, freq, phase):
    return base - amp * (0.6 * math.sin(x * freq + phase) + 0.4 * math.sin(x * freq * 2.3 + phase * 1.7))


# ---------------------------------------------------------------- scene parts
def orb_pos(t):
    """Glowing orb path: rises from Bindu's head, sways, ends at the sky."""
    p = ease_io(prog(t, LAUNCH, BURST_T))
    x = 640 + 70 * math.sin(p * math.pi * 2.2) * (1 - p)
    y = lerp(GROUND - 150, 150, p)
    return x, y


def bindu_state(t):
    """Returns x, y_offset, scale_x, scale_y, look_x, look_y for the character."""
    look = (1.0, 0.0)
    if t < HOP_T1:
        p = prog(t, HOP_T0, HOP_T1)
        x = lerp(-90, 640, ease_out(p) * 0.25 + p * 0.75)
        ph = (p * HOPS) % 1.0 if p < 1 else 0
        lift = 70 * math.sin(math.pi * ph)
        contact = clamp(1 - min(ph, 1 - ph) * 7)
        sy = 1 + 0.12 * math.sin(math.pi * ph) - 0.2 * contact
    else:
        x, lift = 640, 0
        settle = prog(t, HOP_T1, HOP_T1 + 0.5)
        sy = 1 - 0.18 * math.sin(math.pi * settle) * (1 - settle) + 0.02 * math.sin(t * 4)
        look = (0.0, 0.0)
        if t > 6.8:
            look = (0.0, -1.0 * ease_io(prog(t, 6.8, 7.1)))
        if t > LAUNCH and t < BURST_T + 0.3:
            ox, oy = orb_pos(min(t, BURST_T))
            dx, dy = ox - 640, oy - (GROUND - 50)
            d = math.hypot(dx, dy) or 1
            look = (dx / d, dy / d)
        # jump for joy after the burst
        jp = prog(t, 10.25, 10.85)
        if 0 < jp < 1:
            lift = 110 * math.sin(math.pi * jp)
            sy = 1 + 0.15 * math.sin(math.pi * jp)
        if t > 10.85:
            land = prog(t, 10.85, 11.2)
            sy -= 0.22 * math.sin(math.pi * land)
        if t > 10.4:
            look = (0.0, -0.8)
    sx = 1 / math.sqrt(max(sy, 0.5))
    return x, lift, sx, sy, look


def draw_bindu(ctx, t):
    x, lift, sx, sy, (lx, ly) = bindu_state(t)
    R = 46
    # shadow
    shrink = 1 - clamp(lift / 160) * 0.6
    ctx.save()
    ctx.translate(x, GROUND + 4)
    ctx.scale(1, 0.22)
    ctx.set_source_rgba(0, 0, 0, 0.35 * shrink)
    ctx.arc(0, 0, R * 1.05 * shrink, 0, 2 * math.pi)
    ctx.fill()
    ctx.restore()

    # warm light from the orb onto the ground before launch / during float
    ctx.save()
    ctx.translate(x, GROUND - lift)
    tilt = 0.12 * math.sin((t - 12.6) * 6) * prog(t, 12.6, 13.0) if t > 12.6 else 0
    ctx.rotate(tilt)
    ctx.scale(sx, sy)
    # feet
    ctx.set_source_rgb(*hexc("#c4581f"))
    for fx in (-20, 20):
        ctx.save()
        ctx.translate(fx, -5)
        ctx.scale(1.4, 0.7)
        ctx.arc(0, 0, 10, 0, 2 * math.pi)
        ctx.fill()
        ctx.restore()
    # body with soft shading
    g = cairo.RadialGradient(-15, -R - 20, 5, 0, -R, R * 1.3)
    g.add_color_stop_rgb(0, *hexc("#ffd28a"))
    g.add_color_stop_rgb(0.6, *hexc("#ff9f43"))
    g.add_color_stop_rgb(1, *hexc("#e0662a"))
    ctx.set_source(g)
    ctx.arc(0, -R - 4, R, 0, 2 * math.pi)
    ctx.fill()
    # rim light (moon side)
    ctx.set_source_rgba(0.75, 0.85, 1, 0.35)
    ctx.set_line_width(3)
    ctx.arc(0, -R - 4, R - 1.5, -1.3, 0.2)
    ctx.stroke()
    # sprout on head
    ctx.set_source_rgb(*hexc("#5cc46a"))
    ctx.set_line_width(4)
    ctx.move_to(0, -2 * R - 3)
    ctx.curve_to(2, -2 * R - 15, 8, -2 * R - 20, 14, -2 * R - 22)
    ctx.stroke()
    ctx.save()
    ctx.translate(16, -2 * R - 23)
    ctx.rotate(-0.5 + 0.15 * math.sin(t * 3))
    ctx.scale(1.6, 0.8)
    ctx.arc(0, 0, 6, 0, 2 * math.pi)
    ctx.fill()
    ctx.restore()
    # eyes with blink
    blink = 1.0
    for bt in (5.2, 6.85, 12.2):
        d = abs(t - bt)
        if d < 0.09:
            blink = min(blink, 0.1 + d / 0.09 * 0.9)
    for ex in (-16, 16):
        ctx.save()
        ctx.translate(ex, -R - 10)
        ctx.scale(1, blink)
        ctx.set_source_rgb(1, 1, 1)
        ctx.arc(0, 0, 11, 0, 2 * math.pi)
        ctx.fill()
        ctx.set_source_rgb(*hexc("#2a1b3d"))
        ctx.arc(lx * 4.5, ly * 4.5, 6.2, 0, 2 * math.pi)
        ctx.fill()
        ctx.set_source_rgb(1, 1, 1)
        ctx.arc(lx * 4.5 + 2, ly * 4.5 - 2.5, 2, 0, 2 * math.pi)
        ctx.fill()
        ctx.restore()
    # cheeks
    ctx.set_source_rgba(1, 0.45, 0.55, 0.55)
    for cx in (-30, 30):
        ctx.save()
        ctx.translate(cx, -R + 6)
        ctx.scale(1.4, 0.8)
        ctx.arc(0, 0, 6, 0, 2 * math.pi)
        ctx.fill()
        ctx.restore()
    # mouth: smile, opens wide in joy after the burst
    joy = prog(t, 10.1, 10.4)
    ctx.set_source_rgb(*hexc("#5a2330"))
    if joy > 0:
        ctx.save()
        ctx.translate(0, -R + 6)
        ctx.scale(1, 0.4 + 0.6 * joy)
        ctx.arc(0, 0, 9, 0, math.pi)
        ctx.close_path()
        ctx.fill()
        ctx.restore()
    else:
        ctx.set_line_width(3)
        ctx.arc(0, -R + 2, 8, 0.3, math.pi - 0.3)
        ctx.stroke()
    ctx.restore()


def draw_frame(i):
    t = i / FPS
    surf = cairo.ImageSurface(cairo.FORMAT_RGB24, W, H)
    ctx = cairo.Context(surf)

    # slow push-in camera
    zoom = 1 + 0.06 * ease_io(t / DUR)
    ctx.translate(W / 2, H * 0.62)
    ctx.scale(zoom, zoom)
    ctx.translate(-W / 2, -H * 0.62)
    pan = 60 * ease_io(t / DUR)

    # sky: dusk -> night
    n = ease_io(prog(t, 0, 3.2))
    top = lerp_col(hexc("#3a2363"), hexc("#060a22"), n)
    mid = lerp_col(hexc("#c0577a"), hexc("#16204d"), n)
    bot = lerp_col(hexc("#ffae6b"), hexc("#2b3b78"), n)
    g = cairo.LinearGradient(0, 0, 0, H)
    g.add_color_stop_rgb(0, *top)
    g.add_color_stop_rgb(0.55, *mid)
    g.add_color_stop_rgb(1, *bot)
    ctx.set_source(g)
    ctx.rectangle(-100, -100, W + 200, H + 200)
    ctx.fill()

    # stars
    for k, (sx, sy, r, sp, ph) in enumerate(STARS):
        a = prog(t, 0.8 + (k % 40) * 0.06, 2.2 + (k % 40) * 0.06)
        if a <= 0:
            continue
        tw = 0.55 + 0.45 * math.sin(t * sp + ph)
        ctx.set_source_rgba(1, 1, 0.95, a * tw)
        ctx.arc(sx - pan * 0.1, sy, r, 0, 2 * math.pi)
        ctx.fill()

    # moon
    my = lerp(330, 140, ease_out(prog(t, 0, 5)))
    mx = 1040 - pan * 0.15
    glow(ctx, mx, my, 160, hexc("#cfe0ff"), 0.35 * n + 0.1)
    ctx.set_source_rgb(*hexc("#f4f1de"))
    ctx.arc(mx, my, 46, 0, 2 * math.pi)
    ctx.fill()
    ctx.set_source_rgba(0.8, 0.78, 0.7, 0.5)
    for cx, cy, cr in ((-14, -8, 9), (12, 10, 6), (8, -18, 4)):
        ctx.arc(mx + cx, my + cy, cr, 0, 2 * math.pi)
        ctx.fill()

    # hills, 3 parallax layers
    layers = [(470, 60, 0.004, 0.0, "#2c2f6b", "#1a1c45", 0.3),
              (520, 45, 0.006, 2.0, "#1f2557", "#121536", 0.6),
              (565, 30, 0.009, 4.0, "#141a42", "#0b0e26", 1.0)]
    for base, amp, fr, ph, cday, cnight, par in layers:
        col = lerp_col(hexc("#7a3d6e"), hexc(cnight), n) if par < 0.5 else lerp_col(hexc(cday), hexc(cnight), n)
        ctx.set_source_rgb(*col)
        ctx.move_to(-120, H + 100)
        for x in range(-120, W + 140, 8):
            ctx.line_to(x, hill_y(x + pan * par, base, amp, fr, ph))
        ctx.line_to(W + 140, H + 100)
        ctx.close_path()
        ctx.fill()

    # ground
    ctx.set_source_rgb(*lerp_col(hexc("#3b2a55"), hexc("#0a1a24"), n))
    ctx.rectangle(-120, GROUND - 2, W + 260, H)
    ctx.fill()

    # orb light pools on ground
    if LAUNCH - 0.6 < t < BURST_T:
        ox, oy = orb_pos(max(t, LAUNCH))
        a = prog(t, LAUNCH - 0.6, LAUNCH) * (1 - prog(oy, GROUND - 150, 250) * 0.8)
        ctx.save()
        ctx.translate(ox, GROUND + 5)
        ctx.scale(1, 0.25)
        glow(ctx, 0, 0, 220, hexc("#ffd166"), 0.35 * a)
        ctx.restore()

    draw_bindu(ctx, t)

    # orb: appears above head, floats up with sparkle trail
    if LAUNCH - 0.6 < t < BURST_T:
        grow = ease_back(prog(t, LAUNCH - 0.6, LAUNCH))
        ox, oy = orb_pos(max(t, LAUNCH))
        if t > LAUNCH:
            for k in range(1, 30):
                tt = t - k * 0.035
                if tt < LAUNCH:
                    break
                px, py = orb_pos(tt)
                jx = math.sin(k * 12.9 + tt * 7) * k * 0.7
                a = (1 - k / 30) * 0.8
                ctx.set_source_rgba(1, 0.9, 0.55, a)
                ctx.arc(px + jx, py + k * 0.5, 3.5 * (1 - k / 30) + 0.6, 0, 2 * math.pi)
                ctx.fill()
        pulse = 1 + 0.08 * math.sin(t * 10)
        glow(ctx, ox, oy, 90 * grow * pulse, hexc("#ffd166"), 0.9)
        ctx.set_source_rgb(1, 0.98, 0.85)
        ctx.arc(ox, oy, 13 * grow, 0, 2 * math.pi)
        ctx.fill()

    # burst + new star
    sx0, sy0 = orb_pos(BURST_T)
    if t >= BURST_T:
        dt = t - BURST_T
        for ang, spd, r, col in BURST:
            if dt > 1.8:
                break
            drag = (1 - math.exp(-2.2 * dt)) / 2.2
            px = sx0 + math.cos(ang) * spd * drag
            py = sy0 + math.sin(ang) * spd * drag + 40 * dt * dt
            a = clamp(1 - dt / 1.8)
            glow(ctx, px, py, r * 4, col, a * 0.6)
            ctx.set_source_rgba(*col, a)
            ctx.arc(px, py, r * (1 - dt / 2.2), 0, 2 * math.pi)
            ctx.fill()
        ring = ease_out(prog(dt, 0, 0.6))
        if ring < 1:
            ctx.set_source_rgba(1, 0.95, 0.8, 0.7 * (1 - ring))
            ctx.set_line_width(6 * (1 - ring) + 1)
            ctx.arc(sx0, sy0, 20 + 200 * ring, 0, 2 * math.pi)
            ctx.stroke()
        # the new star that remains
        s = ease_back(prog(dt, 0.2, 0.9)) * (1 + 0.1 * math.sin(t * 5))
        glow(ctx, sx0, sy0, 110 * s, hexc("#fff1a8"), 0.7)
        ctx.save()
        ctx.translate(sx0, sy0)
        ctx.rotate(t * 0.4)
        ctx.set_source_rgb(1, 1, 0.92)
        for k in range(8):
            rr = (34 if k % 2 == 0 else 13) * s
            a = k * math.pi / 4
            ctx.line_to(math.cos(a) * rr, math.sin(a) * rr) if k else ctx.move_to(rr, 0)
            a2 = a + math.pi / 8
            ctx.line_to(math.cos(a2) * 6 * s, math.sin(a2) * 6 * s)
        ctx.close_path()
        ctx.fill()
        ctx.restore()

    # foreground grass silhouettes (sway)
    ctx.set_source_rgb(*lerp_col(hexc("#24183a"), hexc("#050d14"), n))
    for gx, gh, lean in GRASS:
        x = gx - pan * 1.4
        sway = lean + 5 * math.sin(t * 1.6 + gx * 0.05)
        ctx.move_to(x - 4, H)
        ctx.curve_to(x - 2, H - gh * 0.5, x, H - gh * 0.8, x + sway, H - gh)
        ctx.curve_to(x + 1, H - gh * 0.8, x + 2, H - gh * 0.5, x + 4, H)
        ctx.close_path()
        ctx.fill()
    ctx.rectangle(-120, H - 18, W + 260, 40)
    ctx.fill()

    # fireflies rising after the burst
    if t > BURST_T + 0.2:
        for fx, fy, delay, rise, ph in FIREFLIES:
            dt = t - BURST_T - 0.2 - delay
            if dt <= 0:
                continue
            px = fx + 18 * math.sin(dt * 1.7 + ph) - pan
            py = fy - rise * dt
            a = clamp(dt / 0.5) * (0.6 + 0.4 * math.sin(dt * 6 + ph))
            glow(ctx, px, py, 16, hexc("#e8ff7a"), 0.7 * a)
            ctx.set_source_rgba(1, 1, 0.8, a)
            ctx.arc(px, py, 2.2, 0, 2 * math.pi)
            ctx.fill()

    ctx.identity_matrix()

    # flash
    if t >= BURST_T:
        f = math.exp(-(t - BURST_T) * 6) * 0.45
        ctx.set_source_rgba(1, 0.95, 0.85, f)
        ctx.paint()

    # title card
    if t > 12.4:
        a = ease_io(prog(t, 12.4, 13.3))
        rise = (1 - a) * 18
        ctx.select_font_face("Inter Display", cairo.FONT_SLANT_NORMAL, cairo.FONT_WEIGHT_BOLD)
        ctx.set_font_size(64)
        txt = "The Little Light"
        ext = ctx.text_extents(txt)
        tx, ty = W / 2 - ext.width / 2 - ext.x_bearing, 345 + rise
        ctx.set_source_rgba(1, 0.8, 0.4, 0.25 * a)
        for ox, oy in ((0, 3), (2, 0), (-2, 0), (0, -2)):
            ctx.move_to(tx + ox, ty + oy)
            ctx.show_text(txt)
        ctx.set_source_rgba(1, 0.97, 0.9, a)
        ctx.move_to(tx, ty)
        ctx.show_text(txt)
        b = ease_io(prog(t, 13.0, 13.8))
        ctx.select_font_face("Inter Display", cairo.FONT_SLANT_NORMAL, cairo.FONT_WEIGHT_NORMAL)
        ctx.set_font_size(22)
        sub = "a  M I T R A  animation"
        ext = ctx.text_extents(sub)
        ctx.set_source_rgba(0.85, 0.88, 1, b * 0.85)
        ctx.move_to(W / 2 - ext.width / 2 - ext.x_bearing, 390 + rise)
        ctx.show_text(sub)

    # vignette
    v = cairo.RadialGradient(W / 2, H / 2, H * 0.35, W / 2, H / 2, H * 0.95)
    v.add_color_stop_rgba(0, 0, 0, 0, 0)
    v.add_color_stop_rgba(1, 0, 0, 0, 0.55)
    ctx.set_source(v)
    ctx.paint()

    # fade in / out
    fade = max(1 - prog(t, 0, 0.6), prog(t, 14.2, 15.0))
    if fade > 0:
        ctx.set_source_rgba(0, 0, 0, fade)
        ctx.paint()

    surf.write_to_png(os.path.join(FRAMES, f"f{i:04d}.png"))


# ---------------------------------------------------------------- music + sfx
SR = 44100


def note(n):  # MIDI -> Hz
    return 440 * 2 ** ((n - 69) / 12)


def make_audio(path):
    N = int(SR * DUR)
    t = np.arange(N) / SR
    out = np.zeros(N)

    def add(sig, start):
        s = int(start * SR)
        e = min(N, s + len(sig))
        if e > s:
            out[s:e] += sig[:e - s]

    # chord progression: Am  F  C  G  (3.75 s each)
    chords = [[57, 60, 64], [53, 57, 60], [48, 52, 55], [55, 59, 62]]
    seg = DUR / 4
    for ci, ch in enumerate(chords):
        L = int(seg * SR * 1.3)
        tt = np.arange(L) / SR
        env = np.minimum(1, tt / 0.8) * np.exp(-np.maximum(0, tt - seg) * 3)
        pad = np.zeros(L)
        for nn in ch:
            f = note(nn)
            for h, amp in ((1, 1), (2, 0.3), (3, 0.12)):
                pad += amp * np.sin(2 * np.pi * f * h * tt + 0.3 * np.sin(2 * np.pi * 0.25 * tt))
                pad += amp * 0.6 * np.sin(2 * np.pi * f * h * 1.004 * tt)
        add(0.03 * pad * env, ci * seg)
        # bass
        fb = note(ch[0] - 12)
        add(0.11 * np.sin(2 * np.pi * fb * tt) * env, ci * seg)
        # arpeggio (starts after dusk)
        step = seg / 12
        pattern = [0, 1, 2, 1, 2, 3, 2, 1, 0, 2, 3, 2]
        tones = ch + [ch[0] + 12]
        for k, pidx in enumerate(pattern):
            st = ci * seg + k * step
            if st < 2.5:
                continue
            f = note(tones[pidx] + 12)
            pl = np.arange(int(0.6 * SR)) / SR
            pluck = (np.sin(2 * np.pi * f * pl) + 0.25 * np.sin(4 * np.pi * f * pl)) * np.exp(-pl * 6)
            add(0.06 * pluck, st)

    # hop blips
    for k in range(HOPS):
        land = HOP_T0 + (HOP_T1 - HOP_T0) * (k + 1) / HOPS
        bl = np.arange(int(0.12 * SR)) / SR
        f = 300 + 40 * k
        add(0.18 * np.sin(2 * np.pi * (f * bl + 900 * bl * bl)) * np.exp(-bl * 35), land - (HOP_T1 - HOP_T0) / HOPS + 0.02)
    # orb appear chime
    cl = np.arange(int(2.0 * SR)) / SR
    for nn, d in ((88, 0), (93, 0.08), (96, 0.16)):
        add(0.08 * np.sin(2 * np.pi * note(nn) * cl) * np.exp(-cl * 2.5), LAUNCH - 0.6 + d)
    # rising shimmer while it floats
    fl = BURST_T - LAUNCH
    sl = np.arange(int(fl * SR)) / SR
    sweep = 600 + 1400 * (sl / fl) ** 2
    phase = 2 * np.pi * np.cumsum(sweep) / SR
    shimmer = np.sin(phase) * (0.5 + 0.5 * np.sin(2 * np.pi * 14 * sl)) * (sl / fl) ** 1.5
    add(0.035 * shimmer, LAUNCH)
    # burst: noise + bell
    bl = np.arange(int(3 * SR)) / SR
    rngn = np.random.default_rng(1)
    noise = rngn.standard_normal(len(bl))
    noise = np.convolve(noise, np.ones(6) / 6, mode="same")
    add(0.25 * noise * np.exp(-bl * 7), BURST_T)
    for nn in (84, 88, 91, 96):
        add(0.07 * np.sin(2 * np.pi * note(nn) * bl) * np.exp(-bl * 1.2), BURST_T + 0.02)
    # joy boing
    jl = np.arange(int(0.35 * SR)) / SR
    add(0.12 * np.sin(2 * np.pi * (350 * jl + 1200 * jl * jl)) * np.exp(-jl * 8), 10.25)

    # master: fade, simple stereo widening, normalize
    fade = np.minimum(1, t / 0.5) * np.clip((DUR - t) / 1.2, 0, 1)
    out *= fade
    out = np.tanh(out * 1.4)
    out /= np.max(np.abs(out)) * 1.12
    dl = int(0.011 * SR)
    left, right = out, np.concatenate([np.zeros(dl), out[:-dl]]) * 0.9 + out * 0.1
    st = (np.stack([left, right], 1) * 32767).astype(np.int16)
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)

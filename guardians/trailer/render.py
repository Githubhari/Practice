SR = 44100


def note(n):
    return 440 * 2 ** ((n - 69) / 12)


def make_audio(path):
    N = int(SR * DUR)
    out = np.zeros(N)
    rng_a = np.random.default_rng(8)

    def add(sig, start, gain=1.0):
        s = int(start * SR)
        e = min(N, s + len(sig))
        if e > s >= 0:
            out[s:e] += gain * sig[:e - s]

    def tl(d):
        return np.arange(int(d * SR)) / SR

    def lp(x, k):
        return np.convolve(x, np.ones(k) / k, mode="same")

    def noise(d):
        return rng_a.standard_normal(int(d * SR))

    def saw(f, tt, nh=12):
        s = np.zeros(len(tt))
        for h in range(1, nh + 1):
            s += np.sin(TAU * f * h * tt) / h
        return s

    def heartbeat(t0, g=1.0):
        for off, amp in ((0, 1), (0.28, 0.7)):
            tt = tl(0.35)
            f = 55 * np.exp(-tt * 3)
            add(np.sin(TAU * np.cumsum(f) / SR) * np.exp(-tt * 14), t0 + off, 0.9 * amp * g)

    def braam(t0, notes, dur=3.5, g=1.0):
        tt = tl(dur)
        s = np.zeros(len(tt))
        for n in notes:
            for det in (1, 1.006, 0.994):
                s += saw(note(n) * det, tt, 8)
        env = np.minimum(1, tt / 0.04) * np.exp(-tt * 1.1)
        add(lp(s, 6) * env / (3 * len(notes)), t0, 0.5 * g)
        add(np.sin(TAU * note(notes[0] - 12) * tt) * env, t0, 0.6 * g)

    def taiko(t0, g=1.0, pitch=1.0):
        tt = tl(1.2)
        f = 130 * pitch * np.exp(-tt * 6) + 45 * pitch
        body = np.sin(TAU * np.cumsum(f) / SR) * np.exp(-tt * 4)
        hit = lp(noise(1.2), 3) * np.exp(-tt * 30)
        add(body + 0.5 * hit, t0, 0.8 * g)

    def whoosh(t0, d, g=1.0, k=12):
        s = lp(noise(d), k) * np.sin(np.linspace(0, math.pi, int(d * SR))) ** 2
        add(s, t0, g)

    def riser(t0, d, f0, f1, g=1.0):
        tt = tl(d)
        f = np.linspace(f0, f1, len(tt))
        s = saw(1, tt, 1) * 0
        ph = TAU * np.cumsum(f) / SR
        s = np.sin(ph) + 0.4 * np.sin(2 * ph) + 0.2 * np.sin(3 * ph)
        add(s * (tt / d) ** 2, t0, g)
        add(lp(noise(d), 3) * (tt / d) ** 3, t0, g * 0.5)

    # --- 0-4 darkness: heartbeat + low drone
    for hb in (0.05, 1.3, 2.5, 3.55):
        heartbeat(hb)
    dr = tl(DUR)
    drone = (saw(note(26), dr, 6) + saw(note(26) * 1.004, dr, 6)) * 0.5
    env = np.clip(dr / 3, 0, 1) * (dr < T_WHITE) + (dr >= T_WHITE) * np.exp(-(dr - T_WHITE) * 6)
    add(lp(drone, 20) * env, 0, 0.18)
    for k in range(10):                                   # stars popping
        add(np.sin(TAU * note(96 - k) * tl(0.2)) * np.exp(-tl(0.2) * 25), 0.6 + k * 0.33, 0.05)
    # --- 4-9 villain rises
    whoosh(T_VILLAIN, 2.6, 0.6, 40)
    riser(T_VILLAIN, T_EYES - T_VILLAIN, 40, 110, 0.12)
    braam(T_EYES, [38, 45, 50], 4.0, 1.3)
    taiko(T_EYES, 1.2, 0.7)
    taiko(7.1, 0.9)
    # --- 9-19.4 hero ostinato (D minor, 16ths)
    six = HERO_LEN / 16
    patt = [50, 50, 62, 50, 53, 50, 62, 50, 52, 50, 60, 50, 53, 50, 57, 50]
    for k in range(4):
        t0 = T_HEROES + k * HERO_LEN
        for j in range(16):
            n = patt[j] + (2 if k == 2 else 0) + (-2 if k == 3 else 0)
            tt = tl(0.16)
            add(lp(saw(note(n), tt, 10), 3) * np.exp(-tt * 18), t0 + j * six, 0.09 + 0.02 * k)
        taiko(t0 + 0.9, 1.1)
        braam(t0 + 0.9, [[38, 45, 50], [41, 48, 53], [36, 43, 48], [34, 41, 46]][k], 2.0, 0.8)
        # element sound
        if k == 0:
            fire = lp(noise(2.0), 6) * (0.6 + 0.4 * np.abs(np.sin(TAU * 7 * tl(2.0))))
            add(fire * np.minimum(1, tl(2.0) / 0.2) * np.exp(-tl(2.0) * 1.2), t0 + 0.3, 0.25)
        elif k == 1:
            for c in range(6):
                cr = noise(0.25)
                cr = cr - lp(cr, 3)
                add(cr * np.exp(-tl(0.25) * 18), t0 + 0.3 + c * 0.32, 0.5)
            add(lp(noise(1.5), 2) * np.exp(-tl(1.5) * 3), t0 + 0.9, 0.3)
        elif k == 2:
            wv = lp(noise(2.0), 30) * (1 + np.sin(TAU * 1.5 * tl(2.0)))
            add(wv * np.minimum(1, tl(2.0) / 0.3), t0 + 0.3, 0.6)
        else:
            add(lp(noise(2.0), 60) * np.exp(-tl(2.0) * 1.0), t0 + 0.35, 1.2)
            for c in range(5):
                taiko(t0 + 0.4 + c * 0.22, 0.25, 1.8)
        whoosh(t0 + HERO_LEN - 0.5, 0.5, 0.4, 8)
    # --- 19.4-23 lineup: building toms
    hits = [T_LINEUP + 0.4]
    tt0 = T_LINEUP + 0.4
    gap = 0.5
    while tt0 < T_CLASH - 0.1:
        tt0 += gap
        gap = max(0.09, gap * 0.85)
        hits.append(tt0)
    for k, h in enumerate(hits):
        taiko(h, 0.4 + 0.6 * k / len(hits), 1.0 + 0.3 * (k % 2))
    braam(T_LINEUP + 0.4, [38, 45, 50, 53], 3.0, 0.9)
    braam(T_LINEUP + 2.0, [43, 50, 55, 58], 1.8, 0.9)        # "ONE LAST LIGHT"
    riser(T_LINEUP + 1.0, T_CLASH - T_LINEUP - 1.0, 200, 900, 0.08)
    # --- 23-28.2 clash
    tt = tl(T_IMPACT - T_CLASH)
    hum = saw(55, tt, 10) * (1 + 0.3 * np.sin(TAU * 6 * tt))
    add(lp(hum, 8) * np.minimum(1, tt / 0.3), T_CLASH, 0.12)
    for k in range(5):
        taiko(T_CLASH + k * 0.2, 0.9)
    eighth = 0.15
    for j in range(int((T_IMPACT - T_CLASH) / eighth)):
        n = [62, 62, 65, 62, 64, 62, 60, 62][j % 8]
        t16 = tl(0.13)
        add(lp(saw(note(n), t16, 10), 3) * np.exp(-t16 * 20), T_CLASH + j * eighth, 0.08)
        if j % 4 == 0:
            taiko(T_CLASH + j * eighth, 0.5)
    for b in (24.2, 25.6, 26.6):
        braam(b, [38, 45, 50, 57], 1.5, 1.0)
    riser(25.0, T_IMPACT - 25.0, 300, 1500, 0.12)
    sp = noise(T_IMPACT - T_CLASH)
    add((sp - lp(sp, 3)) * 0.5, T_CLASH, 0.12)
    # impact
    braam(T_IMPACT, [26, 33, 38], 3.0, 1.6)
    taiko(T_IMPACT, 1.5, 0.6)
    add(lp(noise(2.5), 2) * np.exp(-tl(2.5) * 2.5), T_IMPACT, 0.6)
    # --- 29.3-33 Bindu: silence, then hope
    heartbeat(T_BINDU + 0.5, 0.7)
    tt = tl(1.6)
    add((np.sin(TAU * note(86) * tt) + 0.3 * np.sin(TAU * note(98) * tt)) * np.exp(-tt * 2), T_BINDU + 0.6, 0.15)
    tt = tl(T_TITLE - T_BINDU - 1.0)
    pad = np.zeros(len(tt))
    for n in (50, 57, 62, 66, 69):
        pad += np.sin(TAU * note(n) * tt) + 0.3 * np.sin(TAU * 2 * note(n) * tt)
    add(pad * (tt / tt[-1]) ** 2 / 5, T_BINDU + 1.0, 0.35)
    add(np.sin(TAU * note(81) * tl(0.8)) * np.exp(-tl(0.8) * 3), T_BINDU + 2.5, 0.12)
    riser(T_BINDU + 1.6, T_TITLE - T_BINDU - 1.6, 300, 1200, 0.1)
    # --- 33 title
    braam(T_TITLE, [38, 45, 50, 54, 57], 4.5, 1.5)
    taiko(T_TITLE, 1.5, 0.7)
    cym = noise(4.0)
    add((cym - lp(cym, 2)) * np.exp(-tl(4.0) * 1.2), T_TITLE, 0.35)
    for k, n in enumerate((74, 78, 81, 86, 90)):
        add(np.sin(TAU * note(n) * tl(1.5)) * np.exp(-tl(1.5) * 3), 35.0 + k * 0.2, 0.1)
    taiko(T_SOON, 0.8, 0.8)

    # simple reverb via FFT convolution
    ir_t = tl(1.8)
    ir = rng_a.standard_normal(len(ir_t)) * np.exp(-ir_t * 3.5)
    ir[0] = 0
    L = 1 << int(np.ceil(np.log2(N + len(ir))))
    wet = np.fft.irfft(np.fft.rfft(out, L) * np.fft.rfft(ir, L), L)[:N]
    wet /= np.max(np.abs(wet)) + 1e-9
    mix = out / (np.max(np.abs(out)) + 1e-9) + 0.25 * wet
    # gate the silence beat before the Bindu reveal
    t = np.arange(N) / SR
    mix *= 1 - 0.85 * ((t > T_WHITE + 1.0) & (t < T_BINDU + 0.45))
    mix *= np.clip((DUR - t) / 1.0, 0, 1)
    mix = np.tanh(mix * 1.5)
    mix /= np.max(np.abs(mix)) * 1.05
    dl = int(0.013 * SR)
    left = mix
    right = np.concatenate([np.zeros(dl), mix[:-dl]]) * 0.8 + mix * 0.2
    st = (np.stack([left, right], 1) * 32767).astype(np.int16)
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(st.tobytes())



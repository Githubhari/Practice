# ------------------------------------------------------------------ helpers
def clamp(x, a=0.0, b=1.0):
    return max(a, min(b, x))


def prog(t, t0, t1):
    return clamp((t - t0) / (t1 - t0))


def ease_io(x):
    return x * x * (3 - 2 * x)


def ease_out(x):
    return 1 - (1 - x) ** 3


def ease_in(x):
    return x ** 3


def lerp(a, b, x):
    return a + (b - a) * x


def hexc(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def glow(ctx, x, y, r, col, a=1.0):
    if r <= 0 or a <= 0:
        return
    g = cairo.RadialGradient(x, y, 0, x, y, r)
    g.add_color_stop_rgba(0, *col, a)
    g.add_color_stop_rgba(0.25, *col, a * 0.4)
    g.add_color_stop_rgba(1, *col, 0)
    ctx.set_source(g)
    ctx.arc(x, y, r, 0, TAU)
    ctx.fill()


def text(ctx, txt, x, y, size, col, a=1.0, font=FONT_BLACK, spacing=0.0, glow_col=None, anchor="c"):
    ctx.select_font_face(font, cairo.FONT_SLANT_NORMAL, cairo.FONT_WEIGHT_NORMAL)
    ctx.set_font_size(size)
    widths = [ctx.text_extents(ch).x_advance for ch in txt]
    total = sum(widths) + spacing * (len(txt) - 1)
    x0 = x - total / 2 if anchor == "c" else x

    def put(dx, dy):
        cx = x0 + dx
        for ch, w in zip(txt, widths):
            ctx.move_to(cx, y + dy)
            ctx.show_text(ch)
            cx += w + spacing
    if glow_col:
        for k, (ox, oy) in enumerate(((0, 0), (4, 0), (-4, 0), (0, 4), (0, -4), (6, 6), (-6, -6))):
            ctx.set_source_rgba(*glow_col, 0.18 * a)
            put(ox, oy)
    if isinstance(col, cairo.Pattern):
        ctx.set_source(col)
    else:
        ctx.set_source_rgba(*col, a)
    put(0, 0)
    return total


RNG = random.Random(5)

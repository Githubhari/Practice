def eye_mode(t):
    if 1.1 <= t < 1.85 or t >= 34.05:
        return "cross"
    if 1.9 <= t < 2.25:
        return "squeeze"
    for a, b in ((5.8, 6.65), (16.2, 16.75), (STAR_T, STAR_T + 0.9)):
        if a <= t < b:
            return "happy"
    return "normal"


def look_dir(t):
    def towards(px, py):
        x, lift, _, sy, _ = bindu_body(t)
        dx, dy = px - x, py - (G - lift - R * sy)
        d = math.hypot(dx, dy) or 1
        return dx / d, dy / d
    if t < 1.0 or 33.0 <= t < 34.05:
        hf = hero_flakes(t)
        if hf:
            return towards(hf[0][0], hf[0][1])
    if 2.25 <= t < 3.5:
        return math.sin(t * 4), -0.3
    if 3.5 <= t < 4.6:
        return 0.9, -0.3
    if 4.6 <= t < 5.8:
        hf = hero_flakes(t)
        return towards(hf[-1][0], hf[-1][1]) if hf else (0, -1)
    if 6.65 <= t < 9.0:
        return -1, 0.1
    if 9.0 <= t < 12.0:
        return 1, 0.25
    for t0, t1, r, ty in THROWS:
        if t0 - 0.2 <= t < t1 + 0.2:
            return towards(*throw_pos(min(t, t1), t0, t1, ty))
    if 14.0 <= t < 17.0:
        return 0.9, -0.5
    if 17.0 <= t < ORB_T0:
        return 1, -0.2
    if ORB_T0 <= t < ORB_IN:
        return towards(*orb_pos(t))
    if ORB_IN <= t < STAR_T:
        k = int(clamp((t - LIGHT_T0) / LIGHT_DT, 0, N_LIGHTS - 1))
        return towards(*light_xy(k))
    return 0, 0


def mouth_mode(t):
    if 1.45 <= t < 1.95:
        return "o_small"
    if 1.95 <= t < 2.25:
        return "wide"
    if 5.2 <= t < 5.78 or t >= 34.05:
        return "o"
    if 16.2 <= t < 16.75 or STAR_T <= t < STAR_T + 0.9 or 25.0 <= t < 28.5:
        return "open"
    return "smile"


def draw_bindu(ctx, t):
    x, lift, sx, sy, lean = bindu_body(t)
    shrink = 1 - clamp(lift / 180) * 0.6
    ctx.set_source_rgba(0.3, 0.4, 0.65, 0.4 * shrink)
    ellipse(ctx, x, G + 4, R * 1.05 * shrink, R * 0.2 * shrink)
    ctx.fill()

    ctx.save()
    ctx.translate(x, G - lift)
    ctx.rotate(lean)
    ctx.scale(sx, sy)
    cy = -R - 4
    # feet
    ctx.set_source_rgb(*hexc("#c4581f"))
    for fx in (-0.43 * R, 0.43 * R):
        ellipse(ctx, fx, -6, 0.3 * R, 0.15 * R)
        ctx.fill()
    # body
    g = cairo.RadialGradient(-0.33 * R, cy - 0.45 * R, 0.1 * R, 0, cy, R * 1.3)
    g.add_color_stop_rgb(0, *hexc("#ffd28a"))
    g.add_color_stop_rgb(0.6, *hexc("#ff9f43"))
    g.add_color_stop_rgb(1, *hexc("#e0662a"))
    ctx.set_source(g)
    ctx.arc(0, cy, R, 0, TAU)
    ctx.fill()
    ctx.set_source_rgba(0.75, 0.85, 1, 0.4)
    ctx.set_line_width(3)
    ctx.arc(0, cy, R - 1.5, -1.3, 0.2)
    ctx.stroke()
    # red scarf (clipped to body) + fluttering tail
    ctx.save()
    ctx.arc(0, cy, R, 0, TAU)
    ctx.clip()
    ctx.set_source_rgb(*hexc("#e63946"))
    ctx.rectangle(-R, cy + 0.38 * R, 2 * R, 0.26 * R)
    ctx.fill()
    ctx.set_source_rgb(*hexc("#ffffff"))
    for k in range(-4, 5):
        ctx.rectangle(k * 0.24 * R - 3, cy + 0.38 * R, 6, 0.26 * R)
    ctx.fill()
    ctx.restore()
    flap = math.sin(t * 7) * 0.25
    ctx.set_source_rgb(*hexc("#e63946"))
    ctx.save()
    ctx.translate(0.55 * R, cy + 0.5 * R)
    ctx.rotate(0.35 + flap)
    ctx.rectangle(0, -0.1 * R, 0.24 * R, 0.6 * R)
    ctx.fill()
    ctx.restore()
    # sprout
    ctx.set_source_rgb(*hexc("#5cc46a"))
    ctx.set_line_width(5)
    top = cy - R
    ctx.move_to(0, top + 2)
    ctx.curve_to(2, top - 14, 9, top - 20, 17, top - 23)
    ctx.stroke()
    ctx.save()
    ctx.translate(20, top - 24)
    ctx.rotate(-0.5 + 0.15 * math.sin(t * 3))
    ctx.scale(1.6, 0.8)
    ctx.arc(0, 0, 8, 0, TAU)
    ctx.fill()
    ctx.restore()
    # snow cap on sprout leaf after it starts snowing heavily
    # eyes
    mode = eye_mode(t)
    lx, ly = look_dir(t)
    blink = 1.0
    for bt in (3.0, 8.7, 13.0, 17.2, 27.3, 30.6, 32.8):
        d = abs(t - bt)
        if d < 0.09:
            blink = min(blink, 0.1 + d / 0.09 * 0.9)
    ey = cy - 0.18 * R
    for side, ex in ((-1, -0.34 * R), (1, 0.34 * R)):
        ctx.save()
        ctx.translate(ex, ey)
        if mode == "happy" or mode == "squeeze":
            ctx.set_source_rgb(*hexc("#2a1b3d"))
            ctx.set_line_width(4)
            ctx.set_line_cap(cairo.LINE_CAP_ROUND)
            if mode == "happy":
                ctx.arc(0, 4, 9, math.pi + 0.3, TAU - 0.3)
            else:
                ctx.move_to(-9 * side, -7)
                ctx.line_to(7 * side, 0)
                ctx.line_to(-9 * side, 7)
            ctx.stroke()
            ctx.restore()
            continue
        ctx.scale(1, blink)
        ctx.set_source_rgb(1, 1, 1)
        ctx.arc(0, 0, 0.24 * R, 0, TAU)
        ctx.fill()
        if mode == "cross":
            px, py = -side * 0.75, -0.55
        else:
            px, py = lx, ly
        pr = 0.1 * R
        ctx.set_source_rgb(*hexc("#2a1b3d"))
        ctx.arc(px * pr, py * pr, 0.135 * R, 0, TAU)
        ctx.fill()
        ctx.set_source_rgb(1, 1, 1)
        ctx.arc(px * pr + 3, py * pr - 3.5, 3, 0, TAU)

def draw_frame(i):
    t = i / FPS
    surf = cairo.ImageSurface(cairo.FORMAT_RGB24, W, H)
    ctx = cairo.Context(surf)
    dx, dy = shake(t)
    ctx.translate(dx, dy)
    ctx.translate(W / 2, H / 2)
    ctx.scale(1.04, 1.04)
    ctx.translate(-W / 2, -H / 2)
    if t < T_REWIND:
        scene_hook(ctx, t)
    elif t < T_RACE:
        scene_rewind(ctx, t)
    elif t < T_STORM:
        scene_race(ctx, t)
    elif t < T_HERO:
        scene_storm(ctx, t)
    elif t < T_END:
        scene_hero(ctx, t)
    else:
        scene_end(ctx, t)
    ctx.identity_matrix()
    v = cairo.RadialGradient(W / 2, H / 2, H * 0.3, W / 2, H / 2, H * 0.72)
    v.add_color_stop_rgba(0, 0, 0, 0, 0)
    v.add_color_stop_rgba(1, 0, 0, 0, 0.6)
    ctx.set_source(v)
    ctx.paint()
    if T_RACE <= t < T_STRIKE:
        ctx.set_source_rgba(0.35, 0.2, 0.08, 0.1)
        ctx.paint()
    if t > DUR - 0.6:
        ctx.set_source_rgba(0, 0, 0, prog(t, DUR - 0.6, DUR))
        ctx.paint()
    surf.flush()
    impact = 0
    if T_STRIKE <= t < T_STRIKE + 0.4:
        impact = 1 + (int((t - T_STRIKE) * FPS) // 2) % 2
    post(surf, t, 0)
    if impact:
        arr = np.ndarray((H, W, 4), np.uint8, surf.get_data())
        lum = arr[..., :3].mean(axis=2)
        bw = (lum > 60) if impact == 1 else (lum <= 60)
        arr[..., 0] = np.where(bw, 255, 20)      # B  (cairo stores BGRA)
        arr[..., 1] = np.where(bw, 220, 10)      # G
        arr[..., 2] = np.where(bw, 150, 5)       # R
    surf.mark_dirty()
    surf.write_to_png(os.path.join(FRAMES, f"f{i:04d}.png"))


# ------------------------------------------------------------------ score + sound design
SR = 44100


def note(n):
    return 440 * 2 ** ((n - 69) / 12)


def make_audio(path):
    N = int(SR * DUR)
    out = np.zeros(N)
    rng = np.random.default_rng(22)

    def add(sig, start, gain=1.0):
        s = int(start * SR)
        e = min(N, s + len(sig))
        if e > s >= 0:
            out[s:e] += gain * sig[:e - s]

    def tl(d):
        return np.arange(int(d * SR)) / SR

    def lp(x, k):
        return np.convolve(x, np.ones(k) / k, mode="same")

    def noise(d):
        return rng.standard_normal(int(d * SR))

    def saw(f, tt, nh=10):
        return sum(np.sin(TAU * f * h * tt) / h for h in range(1, nh + 1))

    def braam(t0, notes, dur=3.0, g=1.0):
        tt = tl(dur)
        s = sum(saw(note(n) * d, tt, 8) for n in notes for d in (1, 1.006, 0.994))
        env = np.minimum(1, tt / 0.04) * np.exp(-tt * 1.1)
        add(lp(s, 6) * env / (3 * len(notes)), t0, 0.5 * g)
        add(np.sin(TAU * note(notes[0] - 12) * tt) * env, t0, 0.6 * g)

    def taiko(t0, g=1.0, pitch=1.0):
        tt = tl(1.2)
        f = 130 * pitch * np.exp(-tt * 6) + 45 * pitch
        add(np.sin(TAU * np.cumsum(f) / SR) * np.exp(-tt * 4) + 0.5 * lp(noise(1.2), 3) * np.exp(-tt * 30), t0, 0.8 * g)

    def heartbeat(t0, g=1.0):
        for off, amp in ((0, 1), (0.26, 0.7)):
            tt = tl(0.35)
            f = 55 * np.exp(-tt * 3)
            add(np.sin(TAU * np.cumsum(f) / SR) * np.exp(-tt * 14), t0 + off, 0.9 * amp * g)

    def crack(t0, g=1.0, d=0.3):
        n = noise(d)
        add((n - lp(n, 3)) * np.exp(-tl(d) * 14), t0, g)

    def thunder(t0, g=1.0, d=3.0):
        n = lp(noise(d), 80)
        tt = tl(d)
        add(n * np.minimum(1, tt / 0.05) * np.exp(-tt * 1.3) * (1 + 0.5 * np.sin(TAU * 3 * tt)), t0, g)

    def whoosh(t0, d, g=1.0, k=8):
        add(lp(noise(d), k) * np.sin(np.linspace(0, math.pi, int(d * SR))) ** 2, t0, g)

    def riser(t0, d, f0, f1, g=1.0):
        tt = tl(d)
        ph = TAU * np.cumsum(np.linspace(f0, f1, len(tt))) / SR
        add((np.sin(ph) + 0.4 * np.sin(2 * ph)) * (tt / d) ** 2 + 0.5 * lp(noise(d), 3) * (tt / d) ** 3, t0, g)

    def pad(notes, t0, d, g=1.0):
        tt = tl(d)
        s = sum(np.sin(TAU * note(n) * dt * tt) for n in notes for dt in (1, 1.004))
        add(s * np.minimum(1, tt / 0.8) * np.minimum(1, (d - tt) / 0.8) / len(notes), t0, g)

    def bell(t0, g=1.0, f=330):
        tt = tl(4.0)
        s = sum(a * np.sin(TAU * f * m * tt) * np.exp(-tt * dcy)
                for m, a, dcy in ((1, 1, 0.9), (2.76, 0.5, 1.5), (5.4, 0.3, 2.5), (8.9, 0.15, 4)))
        add(s * np.minimum(1, tt / 0.002), t0, g)

    def pluck(n, t0, g=1.0, d=0.15):
        tt = tl(d)
        add(lp(saw(note(n), tt, 10), 3) * np.exp(-tt * 18), t0, g)

    # hook: zip whooshes + crackles, landing hit
    for k in range(5):
        whoosh(k * 0.18, 0.25, 0.5, 4)
        crack(k * 0.18 + 0.05, 0.35, 0.15)
    taiko(1.0, 1.4, 0.7)
    braam(1.0, [40, 47, 52], 2.4, 1.2)
    crack(1.0, 0.8, 0.5)
    # rewind
    tt = tl(0.8)
    add(np.sin(TAU * np.cumsum(np.linspace(600, 40, len(tt))) / SR) * np.exp(-tt * 2), T_REWIND, 0.3)
    add((lp(noise(0.8), 6) * np.exp(-tl(0.8) * 4))[::-1], T_REWIND, 0.6)
    # race: playful pizzicato in G major, footsteps, crowd; then a sad turn
    step = 0.2
    race_notes = [67, 71, 74, 71, 67, 71, 74, 79, 69, 72, 76, 72, 66, 69, 74, 69]
    for j in range(int((7.4 - T_RACE) / step)):
        pluck(race_notes[j % 16], T_RACE + j * step, 0.08)
        if j % 2 == 0:
            add(lp(noise(0.05), 3) * np.exp(-tl(0.05) * 60), T_RACE + j * step, 0.12)
    crowd = lp(noise(3.0), 6) * (0.5 + 0.5 * np.abs(np.sin(TAU * 2.3 * tl(3.0))))
    add(crowd * np.minimum(1, tl(3.0) / 0.4) * np.minimum(1, (3.0 - tl(3.0)) / 0.8), 6.6, 0.35)
    for n, t0, d in ((71, 7.6, 0.6), (69, 8.2, 0.5), (66, 8.7, 0.9)):
        tt = tl(d)
        add(np.sin(TAU * note(n) * tt) * np.exp(-tt * 2.5), t0, 0.12)
    # storm: rain bed, thunder on flashes, tense ostinato, heartbeat
    rain_len = T_HERO - T_STORM + 5
    rn = noise(rain_len)
    rain = (rn - lp(rn, 2)) * 0.5 + lp(rn, 8) * 0.3
    tt = tl(rain_len)
    abs_t = T_STORM + tt
    rain_env = np.minimum(1, tt / 0.6) * np.where((abs_t > T_FREEZE) & (abs_t < T_UNFREEZE), 0.05, 1.0)
    add(rain * rain_env, T_STORM, 0.2)
    for ft in STORM_FLASHES:
        crack(ft, 0.25, 0.2)
        thunder(ft + 0.15, 0.9)
    pad([40, 47, 52], T_STORM, T_STRIKE - T_STORM, 0.12)
    patt = [52, 52, 64, 52, 55, 52, 64, 52, 54, 52, 62, 52, 55, 52, 59, 52]
    j, tt0 = 0, T_STORM + 0.5
    while tt0 < T_STRIKE:
        pluck(patt[j % 16], tt0, 0.06 + 0.05 * prog(tt0, T_STORM, T_STRIKE))
        j += 1
        tt0 += 0.16
    braam(10.0, [39, 46, 51], 3.0, 0.9)              # shadow eyes
    growl = lp(saw(41, tl(T_STRIKE - 10.0), 12), 10) * (0.6 + 0.4 * np.sin(TAU * 7 * tl(T_STRIKE - 10.0)))
    add(growl * np.minimum(1, tl(T_STRIKE - 10.0) / 2), 10.0, 0.1)
    hb, gap = 13.0, 0.9
    while hb < T_STRIKE - 0.3:
        heartbeat(hb, 0.8)
        hb += gap
        gap = max(0.32, gap * 0.88)
    riser(15.5, T_STRIKE - 15.5, 150, 1500, 0.14)
    # strike
    crack(T_STRIKE, 1.2, 0.6)
    thunder(T_STRIKE, 1.6, 4.0)
    braam(T_STRIKE, [40, 47, 52, 59], 3.0, 1.5)
    taiko(T_STRIKE, 1.6, 0.6)
    # frozen time: muffled, high shimmer, slow heartbeat
    tt = tl(T_UNFREEZE - T_FREEZE)
    shimmer = np.sin(TAU * 1760 * tt) * (0.5 + 0.5 * np.sin(TAU * 0.5 * tt)) * np.minimum(1, tt / 0.5)
    add(shimmer * np.minimum(1, (tt[-1] - tt) / 0.3), T_FREEZE, 0.03)
    pad([52, 59, 64, 71], T_FREEZE, T_UNFREEZE - T_FREEZE, 0.14)
    for hb in (19.2, 20.8, 22.4):
        heartbeat(hb, 0.6)
    add((lp(noise(1.0), 6) * np.exp(-tl(1.0) * 3))[::-1], T_ZIP - 1.0, 0.5)
    # zip: whooshes, cracks, strikes on the shadow, bell
    for k in range(12):
        whoosh(T_ZIP + k * 0.13, 0.2, 0.5, 4)
        crack(T_ZIP + k * 0.13 + 0.03, 0.3, 0.12)
    for ts in (23.5, 23.9, 24.3):
        crack(ts, 0.9, 0.4)
        taiko(ts, 0.8, 0.9)
    braam(T_LAND, [40, 47, 52], 2.5, 1.0)
    for k, tb in enumerate((T_LAND, T_LAND + 0.9, T_LAND + 1.8)):
        bell(tb, 0.35 - 0.08 * k)
    # hero: ostinato + brass theme
    j, tt0 = 0, T_HERO
    while tt0 < T_END:
        pluck(patt[j % 16], tt0, 0.1)
        if j % 8 == 0:
            taiko(tt0, 0.5)
        j += 1
        tt0 += 0.16
    crack(T_HERO, 1.0, 0.5)
    thunder(T_HERO, 1.0, 3.0)
    pad([40, 47, 52, 55], T_HERO, T_END - T_HERO + 0.8, 0.12)
    braam(T_SLAM, [40, 47, 52, 56], 3.5, 1.4)
    taiko(T_SLAM, 1.4, 0.7)
    theme = [(64, 0.32), (71, 0.32), (76, 0.64), (74, 0.32), (71, 0.32), (74, 0.32), (76, 1.6)]
    tm = 27.6
    for n, d in theme:
        tt = tl(d * 1.1)
        env = np.minimum(1, tt / 0.03) * np.exp(-tt * 0.8) * np.minimum(1, (d * 1.1 - tt) / 0.1)
        add(lp(saw(note(n), tt, 9) + saw(note(n) * 1.005, tt, 9), 4) * env, tm, 0.09)
        tm += d
    # end card: water tease
    wv = lp(noise(2.0), 30) * (1 + np.sin(TAU * 1.5 * tl(2.0)))
    add(wv * np.minimum(1, tl(2.0) / 0.3), T_END + 0.8, 0.5)
    taiko(T_END + 1.0, 1.2, 0.8)
    braam(T_END + 1.0, [36, 43, 48], 2.8, 1.0)

    ir_t = tl(1.6)
    ir = rng.standard_normal(len(ir_t)) * np.exp(-ir_t * 3.5)
    ir[0] = 0
    L = 1 << int(np.ceil(np.log2(N + len(ir))))
    wet = np.fft.irfft(np.fft.rfft(out, L) * np.fft.rfft(ir, L), L)[:N]
    mix = out / (np.max(np.abs(out)) + 1e-9) + 0.25 * wet / (np.max(np.abs(wet)) + 1e-9)
    t = np.arange(N) / SR
    mix *= np.clip((DUR - t) / 0.8, 0, 1)
    mix = np.tanh(mix * 1.5)
    mix /= np.max(np.abs(mix)) * 1.05
    dl = int(0.013 * SR)
    right = np.concatenate([np.zeros(dl), mix[:-dl]]) * 0.8 + mix * 0.2
    st = (np.stack([mix, right], 1) * 32767).astype(np.int16)
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(st.tobytes())



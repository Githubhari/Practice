def hero_path(ctx, pose, u, t, fill_rgba):
    """Draw silhouette of a hero in local coords (hip at origin)."""
    p = POSES[pose]
    b = p["broad"]
    ctx.set_source_rgba(*fill_rgba)
    # cape
    if p.get("cape", True):
        wave = math.sin(t * 5) * 0.06
        ctx.move_to(-0.24 * b * u, -0.9 * u)
        ctx.curve_to(-0.5 * u, -0.3 * u, -0.7 * u, 0.3 * u, (-0.75 + wave) * u, 0.75 * u)
        ctx.line_to((-0.35 + wave) * u, 0.65 * u)
        ctx.curve_to(-0.2 * u, 0.2 * u, 0.1 * u, -0.4 * u, 0.24 * b * u, -0.9 * u)
        ctx.close_path()
        ctx.fill()
    # torso
    ctx.move_to(-0.27 * b * u, -0.92 * u)
    ctx.line_to(0.27 * b * u, -0.92 * u)
    ctx.line_to(0.16 * b * u, -0.38 * u)
    ctx.line_to(0.17 * u, 0.06 * u)
    ctx.line_to(-0.17 * u, 0.06 * u)
    ctx.line_to(-0.16 * b * u, -0.38 * u)
    ctx.close_path()
    ctx.fill()
    # head + neck
    ctx.rectangle(-0.06 * u, -1.05 * u, 0.12 * u, 0.16 * u)
    ctx.fill()
    ctx.save()
    ctx.translate(0, -1.17 * u)
    ctx.scale(0.13 * u, 0.16 * u)
    ctx.arc(0, 0, 1, 0, TAU)
    ctx.restore()
    ctx.fill()
    # limbs
    ctx.set_line_cap(cairo.LINE_CAP_ROUND)
    ctx.set_line_join(cairo.LINE_JOIN_ROUND)
    for limb, wdt in [(a, 0.13 * b) for a in p["arms"]] + [(l, 0.16 * b) for l in p["legs"]]:
        ctx.set_line_width(wdt * u)
        ctx.move_to(limb[0][0] * u, limb[0][1] * u)
        for x, y in limb[1:]:
            ctx.line_to(x * u, y * u)
        ctx.stroke()
    # fists / feet
    for limb in p["arms"]:
        ctx.arc(limb[-1][0] * u, limb[-1][1] * u, 0.09 * b * u, 0, TAU)
        ctx.fill()


def draw_hero(ctx, h, x, y, u, t, power):
    """Rim-lit silhouette with glowing eyes. power 0..1 controls rim + eyes."""
    pose = h["pose"]
    p = POSES[pose]
    ctx.save()
    ctx.translate(x, y)
    ctx.rotate(p["lean"])
    # weapon behind arm (agni spear)
    if pose == "agni":
        ctx.set_source_rgb(0.03, 0.02, 0.02)
        ctx.set_line_width(0.05 * u)
        ctx.move_to(0.3 * u, -0.9 * u)
        ctx.line_to(0.62 * u, -2.0 * u)
        ctx.stroke()
    if power > 0:
        ctx.save()
        ctx.translate(-0.025 * u, -0.02 * u)
        hero_path(ctx, pose, u * 1.02, t, (*h["col"], power))
        ctx.restore()
        ctx.save()
        ctx.translate(0.02 * u, -0.015 * u)
        hero_path(ctx, pose, u * 1.01, t, (*h["col2"], 0.5 * power))
        ctx.restore()
    hero_path(ctx, pose, u, t, (0.02, 0.02, 0.04, 1))
    # eyes
    if power > 0:
        for ex in (-0.05, 0.05):
            glow(ctx, ex * u, -1.2 * u, 0.12 * u, h["col"], power)
            ctx.save()
            ctx.translate(ex * u, -1.2 * u)
            ctx.rotate(0.25 if ex < 0 else -0.25)
            ctx.scale(0.04 * u, 0.012 * u)
            ctx.arc(0, 0, 1, 0, TAU)
            ctx.restore()
            ctx.set_source_rgba(*h["col2"], power)
            ctx.fill()
    ctx.restore()
    # hand positions in world for FX
    hands = []
    c, s = math.cos(p["lean"]), math.sin(p["lean"])
    for limb in p["arms"]:
        hx, hy = limb[-1][0] * u, limb[-1][1] * u
        hands.append((x + hx * c - hy * s, y + hx * s + hy * c))
    return hands


def lightning(ctx, x0, y0, x1, y1, seed, col, width=4, a=1.0, rough=0.25):
    r = random.Random(seed)
    pts = [(x0, y0), (x1, y1)]
    for _ in range(5):
        new = [pts[0]]
        for (ax, ay), (bx, by) in zip(pts, pts[1:]):
            mx, my = (ax + bx) / 2, (ay + by) / 2
            d = math.hypot(bx - ax, by - ay)
            nx, ny = -(by - ay) / (d or 1), (bx - ax) / (d or 1)
            off = r.uniform(-rough, rough) * d
            new += [(mx + nx * off, my + ny * off), (bx, by)]
        pts = new
    for wdt, al, cc in ((width * 5, 0.15, col), (width * 2, 0.4, col), (width * 0.7, 1.0, (1, 1, 1))):
        ctx.set_source_rgba(*cc, al * a)
        ctx.set_line_width(wdt)
        ctx.move_to(*pts[0])
        for p in pts[1:]:
            ctx.line_to(*p)
        ctx.stroke()



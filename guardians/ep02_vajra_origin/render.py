def shake(t):
    amp = sum(s * math.exp(-(t - ts) * 5) for ts, s in SHAKES if t >= ts)
    if 16.0 < t < T_STRIKE:
        amp += 5 * prog(t, 16.0, T_STRIKE)
    r = random.Random(int(t * FPS))
    return r.uniform(-amp, amp), r.uniform(-amp, amp)


# ------------------------------------------------------------------ poses
def run_pose(phase, lean=0.22, broad=0.65, cape=False):
    legs, arms = [], []
    for ph in (phase, phase + math.pi):
        thigh = 0.75 * math.sin(ph)
        bend = 0.2 + 1.2 * max(0.0, math.cos(ph))
        knee = (0.47 * math.sin(thigh), 0.47 * math.cos(thigh))
        sh = thigh - bend
        legs.append([(0, 0), knee, (knee[0] + 0.48 * math.sin(sh), knee[1] + 0.48 * math.cos(sh))])
        ua = -0.9 * math.sin(ph)
        sx, sy = 0.0, -0.86
        el = (sx + 0.3 * math.sin(ua), sy + 0.3 * math.cos(ua))
        fa = ua + 1.6
        arms.append([(sx, sy), el, (el[0] + 0.28 * math.sin(fa), el[1] + 0.28 * math.cos(fa))])
    return dict(arms=arms, legs=legs, lean=lean, broad=broad, cape=cape)



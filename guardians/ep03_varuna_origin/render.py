def draw_frame(i):
    t = i / FPS
    surf = cairo.ImageSurface(cairo.FORMAT_RGB24, W, H)
    ctx = cairo.Context(surf)
    dx, dy = shake(t)
    ctx.translate(dx, dy)
    ctx.translate(W / 2, H / 2)
    ctx.scale(1.04, 1.04)
    ctx.translate(-W / 2, -H / 2)
    if t < T_REWIND:
        scene_hook(ctx, t)
    elif t < T_BEACH:
        scene_rewind(ctx, t)
    elif t < T_STORM:
        scene_beach(ctx, t)
    elif t < T_ENGULF:
        scene_storm(ctx, t)
    elif t < T_RISE:
        scene_underwater(ctx, t)
    elif t < T_HERO:
        scene_rise(ctx, t)
    elif t < T_END:
        scene_hero(ctx, t)
    else:
        scene_end(ctx, t)
    ctx.identity_matrix()
    v = cairo.RadialGradient(W / 2, H / 2, H * 0.3, W / 2, H / 2, H * 0.72)
    v.add_color_stop_rgba(0, 0, 0, 0, 0)
    v.add_color_stop_rgba(1, 0, 0, 0, 0.55)
    ctx.set_source(v)
    ctx.paint()
    if T_BEACH <= t < T_ENGULF:
        ctx.set_source_rgba(0.35, 0.2, 0.08, 0.1)
        ctx.paint()
    if t > DUR - 0.6:
        ctx.set_source_rgba(0, 0, 0, prog(t, DUR - 0.6, DUR))
        ctx.paint()
    surf.flush()
    post(surf, t, 0)
    surf.mark_dirty()
    surf.write_to_png(os.path.join(FRAMES, f"f{i:04d}.png"))


# ------------------------------------------------------------------ score + sound design
SR = 44100


def note(n):
    return 440 * 2 ** ((n - 69) / 12)


def make_audio(path):
    N = int(SR * DUR)
    out = np.zeros(N)
    rng = np.random.default_rng(33)

    def add(sig, start, gain=1.0):
        s = int(start * SR)
        e = min(N, s + len(sig))
        if e > s >= 0:
            out[s:e] += gain * sig[:e - s]

    def tl(d):
        return np.arange(int(d * SR)) / SR

    def lp(x, k):
        return np.convolve(x, np.ones(k) / k, mode="same")

    def noise(d):
        return rng.standard_normal(int(d * SR))

    def saw(f, tt, nh=10):
        return sum(np.sin(TAU * f * h * tt) / h for h in range(1, nh + 1))

    def braam(t0, notes, dur=3.0, g=1.0):
        tt = tl(dur)
        s = sum(saw(note(n) * d, tt, 8) for n in notes for d in (1, 1.006, 0.994))
        env = np.minimum(1, tt / 0.04) * np.exp(-tt * 1.1)
        add(lp(s, 6) * env / (3 * len(notes)), t0, 0.5 * g)
        add(np.sin(TAU * note(notes[0] - 12) * tt) * env, t0, 0.6 * g)

    def taiko(t0, g=1.0, pitch=1.0):
        tt = tl(1.2)
        f = 130 * pitch * np.exp(-tt * 6) + 45 * pitch
        add(np.sin(TAU * np.cumsum(f) / SR) * np.exp(-tt * 4) + 0.5 * lp(noise(1.2), 3) * np.exp(-tt * 30), t0, 0.8 * g)

    def heartbeat(t0, g=1.0):
        for off, amp in ((0, 1), (0.26, 0.7)):
            tt = tl(0.35)
            f = 55 * np.exp(-tt * 3)
            add(np.sin(TAU * np.cumsum(f) / SR) * np.exp(-tt * 14), t0 + off, 0.9 * amp * g)

    def thunder(t0, g=1.0, d=3.0):
        tt = tl(d)
        add(lp(noise(d), 80) * np.minimum(1, tt / 0.05) * np.exp(-tt * 1.3), t0, g)

    def waves(t0, d, period, g=1.0, k=20):
        tt = tl(d)
        env = (0.35 + 0.65 * np.clip(np.sin(TAU * tt / period), 0, 1) ** 2)
        add(lp(noise(d), k) * env * np.minimum(1, tt / 0.5) * np.minimum(1, (d - tt) / 0.5), t0, g)

    def riser(t0, d, f0, f1, g=1.0):
        tt = tl(d)
        ph = TAU * np.cumsum(np.linspace(f0, f1, len(tt))) / SR
        add((np.sin(ph) + 0.4 * np.sin(2 * ph)) * (tt / d) ** 2 + 0.5 * lp(noise(d), 3) * (tt / d) ** 3, t0, g)

    def pad(notes, t0, d, g=1.0):
        tt = tl(d)
        s = sum(np.sin(TAU * note(n) * dt * tt) for n in notes for dt in (1, 1.004))
        add(s * np.minimum(1, tt / 0.8) * np.minimum(1, (d - tt) / 0.8) / len(notes), t0, g)

    def pluck(n, t0, g=1.0, d=0.15):
        tt = tl(d)
        add(lp(saw(note(n), tt, 10), 3) * np.exp(-tt * 18), t0, g)

    def flute(n, t0, d, g=1.0):
        tt = tl(d)
        f = note(n) * (1 + 0.006 * np.sin(TAU * 5.2 * tt) * np.minimum(1, tt / 0.3))
        ph = TAU * np.cumsum(f) / SR
        env = np.minimum(1, tt / 0.08) * np.minimum(1, (d - tt) / 0.15)
        add((np.sin(ph) + 0.15 * np.sin(2 * ph) + lp(noise(d), 3) * 0.05) * env, t0, g)

    # hook: ocean roar rises, freezes with a hit
    tt = tl(1.0)
    add(lp(noise(1.0), 10) * tt ** 2, 0.0, 1.2)
    riser(0.0, 1.0, 80, 300, 0.12)
    braam(1.0, [45, 52, 57], 2.6, 1.3)
    taiko(1.0, 1.4, 0.7)
    tt = tl(1.8)
    add(np.sin(TAU * 1568 * tt) * np.minimum(1, tt / 0.2) * np.exp(-tt * 1.2), 1.0, 0.04)
    # rewind
    tt = tl(0.8)
    add(np.sin(TAU * np.cumsum(np.linspace(600, 40, len(tt))) / SR) * np.exp(-tt * 2), T_REWIND, 0.3)
    add((lp(noise(0.8), 6) * np.exp(-tl(0.8) * 4))[::-1], T_REWIND, 0.6)
    # beach: gentle waves, gulls, calm folk melody (A minor pentatonic)
    waves(T_BEACH, T_STORM - T_BEACH, 4.5, 0.9, 30)
    for k, gt in enumerate((4.3, 6.1, 7.7)):
        tt = tl(0.35)
        add(np.sin(TAU * np.cumsum(np.linspace(1800, 1100, len(tt))) / SR) * np.exp(-tt * 6), gt, 0.05)
    pad([57, 64, 69], T_BEACH, T_STORM - T_BEACH + 0.5, 0.08)
    melody = [(76, 0.6), (79, 0.3), (76, 0.3), (74, 0.6), (72, 0.6), (69, 1.2), (72, 0.6), (74, 0.3),
              (72, 0.3), (69, 0.6), (67, 0.6), (69, 1.4)]
    tm = T_BEACH + 0.3
    for n, d in melody:
        flute(n, tm, d * 1.05, 0.1)
        tm += d
    # storm: heavy sea, thunder, tense ostinato in C minor, growl, heartbeat while she hesitates
    waves(T_STORM, T_ENGULF - T_STORM, 1.8, 1.6, 12)
    for f in STORM_FLASHES:
        n = noise(0.25)
        add((n - lp(n, 3)) * np.exp(-tl(0.25) * 14), f, 0.25)
        thunder(f + 0.15, 0.9)
    pad([48, 55, 60, 63], T_STORM, T_ENGULF - T_STORM, 0.12)
    patt = [48, 48, 60, 48, 51, 48, 60, 48, 50, 48, 58, 48, 51, 48, 55, 48]
    j, t0 = 0, T_STORM + 0.4
    while t0 < T_ENGULF:
        pluck(patt[j % 16], t0, 0.06 + 0.05 * prog(t0, T_STORM, T_ENGULF))
        j += 1
        t0 += 0.16
    braam(10.0, [36, 43, 48], 3.0, 0.9)
    tt = tl(T_ENGULF - 10.0)
    add(lp(saw(41, tt, 12), 10) * (0.6 + 0.4 * np.sin(TAU * 7 * tt)) * np.minimum(1, tt / 2), 10.0, 0.08)
    hb, gap = 13.0, 0.85
    while hb < T_RUN:
        heartbeat(hb, 0.8)
        hb += gap
        gap = max(0.35, gap * 0.88)
    riser(T_RUN, T_ENGULF - T_RUN, 200, 1200, 0.12)
    for k in range(6):                                # splashing footsteps
        add(lp(noise(0.12), 3) * np.exp(-tl(0.12) * 30), T_RUN + k * 0.28, 0.3)
    # engulf: crash, then muffled underwater
    add(lp(noise(1.5), 4) * np.exp(-tl(1.5) * 3), T_ENGULF - 0.1, 1.0)
    taiko(T_ENGULF, 1.2, 0.5)
    tt = tl(T_RISE - T_ENGULF)
    add(lp(noise(T_RISE - T_ENGULF), 200) * 3, T_ENGULF, 0.6)
    for k in range(18):
        bt = T_ENGULF + 0.1 + k * 0.12
        tb = tl(0.06)
        add(np.sin(TAU * np.cumsum(np.linspace(400 + 30 * k, 900 + 40 * k, len(tb))) / SR) * np.exp(-tb * 40), bt, 0.05)
    heartbeat(17.9, 0.7)
    for k, n in enumerate((81, 86, 88, 93)):
        tb = tl(1.5)
        add(np.sin(TAU * note(n) * tb) * np.exp(-tb * 2.5), T_GLOW + k * 0.08, 0.07)
    riser(T_GLOW, T_BLAST - T_GLOW, 200, 1500, 0.14)
    braam(T_BLAST, [45, 52, 57, 64], 3.5, 1.5)
    taiko(T_BLAST, 1.6, 0.6)
    add(lp(noise(2.0), 6) * np.exp(-tl(2.0) * 2), T_BLAST, 0.8)
    # rise + rescue: heroic ostinato in A, big wave roar
    j, t0 = 0, T_RISE
    patt2 = [57, 57, 69, 57, 60, 57, 69, 57, 59, 57, 67, 57, 60, 57, 64, 57]
    while t0 < T_END:
        pluck(patt2[j % 16], t0, 0.09)
        if j % 8 == 0:
            taiko(t0, 0.5)
        j += 1
        t0 += 0.16
    waves(21.0, 5.0, 5.0, 1.4, 15)
    pad([57, 64, 69, 72], T_RISE, T_END - T_RISE + 0.8, 0.12)
    braam(23.4, [45, 52, 57, 61], 2.5, 1.0)
    # hero
    braam(T_SLAM, [45, 52, 57, 61], 3.5, 1.4)
    taiko(T_SLAM, 1.4, 0.7)
    theme = [(69, 0.32), (76, 0.32), (81, 0.64), (79, 0.32), (76, 0.32), (79, 0.32), (81, 1.6)]
    tm = 27.6
    for n, d in theme:
        tt = tl(d * 1.1)
        env = np.minimum(1, tt / 0.03) * np.exp(-tt * 0.8) * np.minimum(1, (d * 1.1 - tt) / 0.1)
        add(lp(saw(note(n), tt, 9) + saw(note(n) * 1.005, tt, 9), 4) * env, tm, 0.09)
        tm += d
    # end: earth tease
    add(lp(noise(2.0), 60) * np.exp(-tl(2.0) * 1.0), T_END + 0.9, 1.2)
    for k in range(5):
        taiko(T_END + 1.0 + k * 0.22, 0.3, 1.8)
    taiko(T_END + 1.0, 1.2, 0.8)
    braam(T_END + 1.0, [38, 45, 50], 2.8, 1.0)

    ir_t = tl(1.6)
    ir = rng.standard_normal(len(ir_t)) * np.exp(-ir_t * 3.5)
    ir[0] = 0
    L = 1 << int(np.ceil(np.log2(N + len(ir))))
    wet = np.fft.irfft(np.fft.rfft(out, L) * np.fft.rfft(ir, L), L)[:N]
    mix = out / (np.max(np.abs(out)) + 1e-9) + 0.25 * wet / (np.max(np.abs(wet)) + 1e-9)
    t = np.arange(N) / SR
    mix *= np.clip((DUR - t) / 0.8, 0, 1)
    mix = np.tanh(mix * 1.5)
    mix /= np.max(np.abs(mix)) * 1.05
    dl = int(0.013 * SR)
    right = np.concatenate([np.zeros(dl), mix[:-dl]]) * 0.8 + mix * 0.2
    st = (np.stack([mix, right], 1) * 32767).astype(np.int16)
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(st.tobytes())



def shake(t):
    amp = 0.0
    for ts, s in SHAKES:
        if t >= ts:
            amp += s * math.exp(-(t - ts) * 5)
    if T_CLASH < t < T_IMPACT:
        amp += 5 + 10 * prog(t, 25.0, T_IMPACT)
    r = random.Random(int(t * FPS))
    return r.uniform(-amp, amp), r.uniform(-amp, amp)



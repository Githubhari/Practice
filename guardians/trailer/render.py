def scene_darkness(ctx, t):
    ctx.set_source_rgb(*hexc("#050b1f"))
    ctx.paint()
    g = cairo.LinearGradient(0, 0, 0, H)
    g.add_color_stop_rgba(0, 0.1, 0.15, 0.35, 0.6)
    g.add_color_stop_rgba(1, 0.2, 0.1, 0.3, 0.6)
    ctx.set_source(g)
    ctx.paint()
    speed = (H + 600) / 3.6
    front = -300 + speed * t

    def edge(x):
        return front + 60 * math.sin(x * 0.012 + t * 3) + 30 * math.sin(x * 0.031 - t * 4)
    for sx, sy, r, ph in STARS:
        tc = (sy + 300 - 60 * math.sin(sx * 0.012)) / speed
        if t < tc:
            a = 0.6 + 0.4 * math.sin(t * 3 + ph)
            ctx.set_source_rgba(1, 1, 0.95, a)
            ctx.arc(sx, sy, r, 0, TAU)
            ctx.fill()
            if r > 2.4:
                glow(ctx, sx, sy, r * 6, (0.8, 0.85, 1), 0.3 * a)
        elif t - tc < 0.25:
            p = (t - tc) / 0.25
            glow(ctx, sx, sy, r * 8 * (1 - p), (1, 0.6, 0.6), 1 - p)
    # darkness mass
    ctx.move_to(-50, -50)
    for x in range(-50, W + 60, 15):
        ctx.line_to(x, edge(x))
    ctx.line_to(W + 50, -50)
    ctx.close_path()
    ctx.set_source_rgb(0.01, 0.0, 0.02)
    ctx.fill()
    ctx.set_line_width(14)
    ctx.move_to(-50, edge(-50))
    for x in range(-50, W + 60, 15):
        ctx.line_to(x, edge(x))
    ctx.set_source_rgba(*hexc("#ff2a3d"), 0.35)
    ctx.stroke()
    # creeping red glints in the dark
    r = random.Random(3)
    for _ in range(25):
        gx, gy = r.uniform(0, W), r.uniform(0, 1)
        y = gy * (front - 100)
        if y > 0:
            glow(ctx, gx, y, 10, hexc("#ff1030"), 0.4 + 0.3 * math.sin(t * 5 + gx))
    a = ease_io(prog(t, 0.2, 0.8)) * (1 - ease_io(prog(t, 3.3, 3.9)))
    text(ctx, "When darkness", W / 2, 1180, 72, (1, 1, 1), a, FONT, 2)
    text(ctx, "swallowed the stars...", W / 2, 1270, 72, (1, 1, 1), a, FONT, 2)



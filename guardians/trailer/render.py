def draw_villain(ctx, cx, top, sc, t, eyes, rim=1.0):
    """Andhakaar: colossal hooded shadow made of smoke."""
    def wob(k, amp=12):
        return amp * math.sin(t * 2.1 + k * 1.7) + amp * 0.5 * math.sin(t * 3.3 + k * 2.9)

    def body_path(off=0.0):
        ctx.move_to(cx + wob(0, 6), top - off)
        ctx.curve_to(cx + 170 * sc + wob(1), top + 40 * sc, cx + 250 * sc, top + 250 * sc,
                     cx + 260 * sc + wob(2), top + 400 * sc)
        ctx.curve_to(cx + 420 * sc + wob(3), top + 460 * sc, cx + 560 * sc, top + 560 * sc,
                     cx + 640 * sc + wob(4, 20), top + 1400 * sc)
        ctx.line_to(cx - 640 * sc + wob(5, 20), top + 1400 * sc)
        ctx.curve_to(cx - 560 * sc, top + 560 * sc, cx - 420 * sc + wob(6), top + 460 * sc,
                     cx - 260 * sc + wob(7), top + 400 * sc)
        ctx.curve_to(cx - 250 * sc, top + 250 * sc, cx - 170 * sc + wob(8), top + 40 * sc,
                     cx + wob(0, 6), top - off)
        ctx.close_path()
    # red aura
    glow(ctx, cx, top + 300 * sc, 700 * sc, hexc("#7a0010"), 0.5 * rim)
    ctx.save()
    ctx.translate(-6, -8)
    body_path(10)
    ctx.set_source_rgba(*hexc("#ff2a3d"), 0.85 * rim)
    ctx.fill()
    ctx.restore()
    body_path()
    g = cairo.LinearGradient(0, top, 0, top + 900 * sc)
    g.add_color_stop_rgb(0, *hexc("#16081c"))
    g.add_color_stop_rgb(1, *hexc("#050208"))
    ctx.set_source(g)
    ctx.fill()
    # hood void
    ctx.save()
    ctx.translate(cx, top + 220 * sc)
    ctx.scale(120 * sc, 150 * sc)
    ctx.arc(0, 0, 1, 0, TAU)
    ctx.restore()
    ctx.set_source_rgb(0, 0, 0)
    ctx.fill()
    # smoke tendrils
    ctx.set_line_cap(cairo.LINE_CAP_ROUND)
    for k in range(9):
        side = -1 if k % 2 else 1
        bx = cx + side * (220 + 40 * k) * sc
        by = top + (380 + 30 * k) * sc
        ctx.set_source_rgba(0.06, 0.02, 0.08, 0.7)
        ctx.set_line_width((26 - k * 2) * sc)
        ctx.move_to(bx, by)
        ctx.curve_to(bx + side * 120 * sc, by - 140 * sc + wob(k, 30),
                     bx + side * 200 * sc, by - 60 * sc, bx + side * (260 + wob(k + 3, 40)) * sc,
                     by - (220 + 20 * k) * sc)
        ctx.stroke()
    # eyes
    if eyes > 0:
        for side in (-1, 1):
            ex, ey = cx + side * 48 * sc, top + 215 * sc
            glow(ctx, ex, ey, 220 * sc * eyes, hexc("#ff1030"), 0.9 * eyes)
            ctx.save()
            ctx.translate(ex, ey)
            ctx.rotate(side * 0.35)
            ctx.move_to(-30 * sc, 0)
            ctx.line_to(0, -9 * sc * eyes)
            ctx.line_to(30 * sc, 0)
            ctx.line_to(0, 6 * sc * eyes)
            ctx.close_path()
            ctx.restore()
            ctx.set_source_rgba(1, 0.85, 0.85, eyes)
            ctx.fill()
    return (cx, top + 215 * sc)


def draw_bindu(ctx, x, y, R, t, eyes_open, glow_a=1.0):
    glow(ctx, x, y, R * 5, hexc("#ffd166"), 0.8 * glow_a)
    g = cairo.RadialGradient(x - R * 0.33, y - R * 0.45, R * 0.1, x, y, R * 1.3)
    g.add_color_stop_rgb(0, *hexc("#fff0c2"))
    g.add_color_stop_rgb(0.6, *hexc("#ffb347"))
    g.add_color_stop_rgb(1, *hexc("#e0662a"))
    ctx.set_source(g)
    ctx.arc(x, y, R, 0, TAU)
    ctx.fill()
    ctx.set_source_rgb(*hexc("#5cc46a"))
    ctx.set_line_width(R * 0.08)
    ctx.move_to(x, y - R)
    ctx.curve_to(x + 2, y - R * 1.2, x + R * 0.15, y - R * 1.3, x + R * 0.28, y - R * 1.35)
    ctx.stroke()
    ctx.save()
    ctx.translate(x + R * 0.32, y - R * 1.37)
    ctx.rotate(-0.5)
